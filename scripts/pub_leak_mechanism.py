"""Publication revision: decompose the back-adjustment term L(t) = log F(t) into a future-dividend part and a
future-price-path part, and measure each part's association with 5-day factor-neutral returns.

  python scripts/pub_leak_mechanism.py   -> docs/publication/LEAK_MECHANISM.md
Uses only data already on disk (audit unadjusted download, 2014-06..2024-01-11; FB saved labels, 2019-2023 signals).
No model, no backtest, no new period. All years were inspected before: descriptive/exploratory.

Identity (multiplicative back-adjustment, factor applied to all dates before ex-date e):
  L(t) = L(end) + sum_{t < e <= end} log(1 - y_e),   y_e = D_e / P_{e-1} = 1 - exp(-(L(e) - L(e-1)))
Counterfactual with today's price in place of the future pre-ex-date price:
  L_div(t) = L(end) + sum_{t < e <= end} log(1 - y_e * P_{e-1} / P(t))    (future dividends, valued at P(t))
  L_path(t) = L(t) - L_div(t)                                             (dependence on the future price path)
L(end) is the factor for distributions after the download window (to the fetch date); it is reported separately.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
from hypershift.fbaudit import stats as S  # noqa: E402

RAW = Path('data/audit/yf_unadjusted/unadjusted.npz')
FB_ROOT = Path('results/FEATBENCH_SP500_20261022')
OUT = Path('docs/publication/LEAK_MECHANISM.md')
TOL = 1e-6


def components(close, adj, signals):
    """Return dict of [S, N] arrays: L, L_div, L_path, L_end, n_ex (future ex-dates in window)."""
    N, T = close.shape
    L = np.log(adj / close)
    out = {k: np.full((len(signals), N), np.nan) for k in ('L', 'L_div', 'L_path', 'L_end')}
    stats = {'ex_dates': 0, 'negative_jumps': 0}
    for i in range(N):
        li, ci = L[i], close[i]
        ok = np.isfinite(li) & np.isfinite(ci)
        if ok.sum() < 300:
            continue
        last = np.flatnonzero(ok)[-1]
        dl = np.full(T, np.nan); dl[1:] = li[1:] - li[:-1]
        ex = np.flatnonzero((dl > TOL) & ok & np.r_[False, ok[:-1]])
        stats['ex_dates'] += len(ex); stats['negative_jumps'] += int(((dl < -TOL) & ok).sum())
        y = 1 - np.exp(-dl[ex])
        pm = ci[ex - 1]
        for d, t in enumerate(signals):
            if not ok[t] or t > last:
                continue
            fut = ex > t
            fut &= ex <= last
            ldiv = li[last] + np.sum(np.log(np.clip(1 - y[fut] * pm[fut] / ci[t], 1e-6, None)))
            out['L'][d, i] = li[t]
            out['L_div'][d, i] = ldiv
            out['L_path'][d, i] = li[t] - ldiv
            out['L_end'][d, i] = li[last]
    return out, stats


def main():
    z = np.load(RAW)
    close, adj = z['close'].astype(np.float64), z['adj'].astype(np.float64)
    ser, sds, cors = {}, {}, {}
    st_tot = None
    for f in S.FOLDS:
        p = S.load_pred(FB_ROOT, f, 'lgbm:rich')
        sig = p['signals']
        comp, st = components(close, adj, sig)
        st_tot = st if st_tot is None else st_tot   # event counts are per stock history: count once, not per fold
        neu = p['neutral'].astype(np.float64)
        m = p['mask'].astype(bool) & np.all([np.isfinite(v) for v in comp.values()], 0)
        for k, v in comp.items():
            ser.setdefault(k, {})[f] = S.spearman_daily(np.nan_to_num(v), neu, m)
            sds.setdefault(k, []).append(np.nanmean([np.nanstd(v[d][m[d]]) for d in range(len(sig))]))
        cors.setdefault('L_div~L_path', []).append(np.nanmean(S.spearman_daily(np.nan_to_num(comp['L_div']), np.nan_to_num(comp['L_path']), m)))
        cors.setdefault('L~L_div', []).append(np.nanmean(S.spearman_daily(np.nan_to_num(comp['L']), np.nan_to_num(comp['L_div']), m)))
        print('fold', f, flush=True)
    fmt = lambda r: f"{r['pooled']:+.4f} [{r['ci95'][0]:+.4f}, {r['ci95'][1]:+.4f}]"
    yrs = lambda r: ' / '.join(f'{v:+.4f}' for v in r['per_fold'].values())
    lab = {'L': 'L(t) = log(AdjClose/Close): full ex-post adjustment term',
           'L_div': 'L_div(t): future distributions valued at today\'s price P(t) (no future-price input inside the window)',
           'L_path': 'L_path(t) = L − L_div: dependence on the future price path (P_{e−1} vs P(t))',
           'L_end': 'L(end): factor for distributions after 2024-01-11 (constant per stock over time)'}
    Lmd = ['# Mechanism decomposition of the back-adjustment term (publication revision)', '',
           'Descriptive analysis on data already on disk: the audit\'s unadjusted download (2014-06 to 2024-01-11) and '
           'the FB saved labels (factor-neutral 5-day returns, 2019–2023 signals, 462 current S&P 500 stocks). '
           'No model is fitted, no backtest is run, and no new period is used. All years were inspected before. '
           'Generated by `scripts/pub_leak_mechanism.py`.', '',
           '**Identity used.** L(t) = L(end) + Σ_{t<e≤end} log(1 − y_e), with y_e = D_e/P_{e−1} recovered from the '
           f'jumps of L at ex-dates. Detected distribution events: {st_tot["ex_dates"]}. Negative jumps of L '
           f'(revisions or rounding; not modelled): {st_tot["negative_jumps"]}.', '',
           '**Counterfactual.** L_div replaces each future pre-ex-date price P_{e−1} with the current price P(t). It keeps '
           'the realised future distribution amounts but removes their dependence on the future price path. L_path is '
           'the remainder. Both components use post-t information: L_div through future dividend amounts, L_path '
           'through future prices.', '',
           '| Component | Rank IC vs 5-day neutral return, pooled [95% CI] | Per year 2019–2023 | Mean cross-sectional SD |',
           '|---|---|---|---|']
    for k in ('L', 'L_div', 'L_path', 'L_end'):
        r = S.pooled(ser[k], 'stationary', 10)
        Lmd.append(f'| {lab[k]} | {fmt(r)} | {yrs(r)} | {np.mean(sds[k]):.4f} |')
    Lmd += ['', f"Mean per-date Spearman correlation: L_div vs L_path {np.mean(cors['L_div~L_path']):+.3f}; L vs L_div {np.mean(cors['L~L_div']):+.3f}.", '',
            '**Reading rules (fixed before the numbers):**',
            '- If L_path carries a positive association, the future-price channel is empirically present.',
            '- If L_div carries a positive association, future distribution amounts (dividend policy outcomes) are associated with returns.',
            '- Neither component is a causal estimate. Both are ex-post quantities unavailable at t, so any association '
            'is look-ahead by construction. Their sizes describe how much predictive content the contamination can '
            'carry in this sample.']
    import json
    res = {k: {kk: (list(vv) if isinstance(vv, tuple) else vv) for kk, vv in S.pooled(ser[k], 'stationary', 10).items()} for k in ser}
    res['_stats'] = st_tot
    Path('docs/publication/figures').mkdir(parents=True, exist_ok=True)
    Path('docs/publication/figures/leak_mechanism.json').write_text(json.dumps(res, indent=1, default=float))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(Lmd) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(Lmd))


if __name__ == '__main__':
    main()
