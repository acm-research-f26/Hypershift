"""Study FB Task 1: OHLCV data audit and power analysis (no model fitting, no 2024+ scoring).

  python scripts/featbench_audit.py --out docs/featbench_20261022
"""
import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'scripts')
from screen_analysis import bootstrap_means  # noqa: E402

PANEL = 'data/fresh/sp500_daily/screen_sp500_2015_2026.npz'
OHLCV = 'data/fresh/sp500_daily/ohlcv_sp500_2015_2026.npz'
V3 = Path('results/SCREEN_SP500_20261019_v3')


def audit():
    p, o = np.load(PANEL), np.load(OHLCV)
    ident = p['identity_ok'].astype(bool)
    dates = p['dates'].astype('datetime64[D]')
    dev = dates < np.datetime64('2024-01-01')  # audit only the development range
    seen = p['mask'].astype(bool) & dev[None]
    x = o['ohlcv'].astype(np.float64)
    op, hi, lo, cl, vo = (x[..., k] for k in range(5))
    pc = p['features'][..., -1].astype(np.float64)
    out = {'stocks': int(len(ident)), 'identity_ok': int(ident.sum()),
           'tickers_aligned': bool((p['tickers'] == o['tickers']).all()),
           'dates_aligned': bool((p['dates'].astype('datetime64[D]') == o['dates'].astype('datetime64[D]')).all()),
           'observed_cells_dev': int(seen.sum())}
    s = seen
    out['nan_ohlcv'] = int((~np.isfinite(x[s])).any(-1).sum())
    out['zero_volume'] = int((vo[s] <= 0).sum())
    out['low_gt_min_oc'] = int((lo[s] > np.minimum(op[s], cl[s]) * (1 + 1e-6)).sum())
    out['high_lt_max_oc'] = int((hi[s] < np.maximum(op[s], cl[s]) * (1 - 1e-6)).sum())
    ratio = cl / np.where(pc > 0, pc, np.nan)
    rr = ratio[s]
    # close/panel-close may differ by a per-stock constant (adjustment base); check constancy
    dev_const = []
    for i in range(len(ident)):
        r = ratio[i][s[i]]
        if len(r):
            dev_const.append(np.nanmax(np.abs(r / np.nanmedian(r) - 1)))
    out['close_vs_panel_max_rel_dev_per_stock'] = float(np.nanmax(dev_const))
    out['close_vs_panel_median_ratio'] = float(np.nanmedian(rr))
    lr = np.zeros_like(cl); lv = np.zeros_like(vo)
    both = s[:, 1:] & s[:, :-1]
    lr[:, 1:] = np.where(both, np.log(np.maximum(cl[:, 1:], 1e-9) / np.maximum(cl[:, :-1], 1e-9)), 0)
    lv[:, 1:] = np.where(both & (vo[:, 1:] > 0) & (vo[:, :-1] > 0),
                         np.log(np.maximum(vo[:, 1:], 1) / np.maximum(vo[:, :-1], 1)), 0)
    out['price_jumps_gt_0.4'] = int((np.abs(lr) > .4).sum())
    out['price_jump_with_volume_jump_gt_3'] = int(((np.abs(lr) > .4) & (np.abs(lv) > 3)).sum())
    out['volume_jumps_gt_3_logs'] = int((np.abs(lv) > 3).sum())
    return out


def power():
    """MDE for a paired daily ΔRankIC contrast between two deterministic scorers."""
    rows = []
    for year in (2022, 2023):
        a = np.load(V3/str(year)/'ridge'/'seed_7'/'daily.npz')
        b = np.load(V3/str(year)/'reversal'/'seed_7'/'daily.npz')
        for key in ('RankIC', 'neutral_RankIC'):
            d = a[key] - b[key]
            boots = bootstrap_means(d, 10, 5000, np.random.default_rng((5, year)))
            rows.append((year, key, len(d), float(d.std(ddof=1)), float(boots.std()),
                         float(d.std(ddof=1) / np.sqrt(len(d)))))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    out = Path(ap.parse_args().out)
    out.mkdir(parents=True, exist_ok=True)
    a = audit()
    L = ['# Study FB data audit (development range 2015-01-02 to 2023-12-31 only)', '',
         'Generated by `scripts/featbench_audit.py`. Cells = panel-observed (stock, day) cells before 2024.', '',
         '| Check | Value |', '|---|---|'] + [f'| {k} | {v} |' for k, v in a.items()]
    L += ['', '## Reading', '',
          '- **Volume and OHLC exist for every observed cell** unless the NaN/zero counts above say otherwise; features treat zero volume through +1 offsets (finite by construction).',
          '- **Adjustment:** OHLCV close equals the panel close up to a per-stock constant (max relative deviation above); both are split/dividend-adjusted yfinance series, so returns agree. Volume is not split-adjusted in a way we can verify; volume features use ratios of trailing means, which a split distorts only for up to 60 sessions after the split.',
          '- **Survivorship:** the universe is the 2026 S&P 500 traced back to 2015 (no delisted stocks). GICS sectors are current, not point-in-time.',
          '- **Not available:** point-in-time fundamentals and shares outstanding. "Size" is proxied by 20-day mean dollar volume, which mixes size and liquidity.']
    (out/'DATA_AUDIT.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    rows = power()
    se_fold = {k: np.mean([r[4] for r in rows if r[1] == k]) for k in ('RankIC', 'neutral_RankIC')}
    n_fold = int(np.mean([r[2] for r in rows]))
    P = ['# Study FB power analysis', '',
         'Source: v3 deterministic baselines `ridge` and `reversal` (seed 7), folds 2022/2023, saved `daily.npz` '
         '(`results/SCREEN_SP500_20261019_v3`). Paired daily ΔRankIC = ridge − reversal. SE of the fold mean from a '
         'stationary bootstrap (block 10, B 5000). MDE = 2.8 × SE (80% power, two-sided α 0.05). Deterministic models '
         'have no seed variance, so date variance is the whole uncertainty.', '',
         '| Fold | Metric | Days | Daily SD | Bootstrap SE of mean | iid SE |', '|---|---|---|---|---|---|']
    P += [f'| {y} | {k} | {n} | {sd:.4f} | {se:.4f} | {iid:.4f} |' for y, k, n, sd, se, iid in rows]
    P += ['', '## Minimum detectable effects', '', '| Design | SE (neutral RankIC) | MDE (neutral) | MDE (raw) |', '|---|---|---|---|']
    for label, nfolds in (('1 fold (~250 days)', 1), ('2 folds', 2), ('5 folds 2019–2023 (pooled mean of fold means)', 5)):
        sn, sr = se_fold['neutral_RankIC'] / np.sqrt(nfolds), se_fold['RankIC'] / np.sqrt(nfolds)
        P.append(f'| {label} | {sn:.4f} | {2.8*sn:.4f} | {2.8*sr:.4f} |')
    P += ['', '## Prospective test length', '', '| Prospective days | MDE (neutral, scaled from the fold SE by √(days)) |', '|---|---|']
    for nd in (60, 125, 250, 500):
        P.append(f'| {nd} | {2.8*se_fold["neutral_RankIC"]*np.sqrt(n_fold/nd):.4f} |')
    need = {m: int(np.ceil(n_fold * (2.8*se_fold['neutral_RankIC']/m)**2)) for m in (.01, .02)}
    P += ['', f'Days needed for MDE 0.01: **{need[.01]}**; for MDE 0.02: **{need[.02]}** (neutral RankIC, paired contrast of two deterministic scorers; a contrast against a weaker or less correlated comparator has a larger SD).',
          '', 'Caveat: estimated from one contrast (ridge vs reversal) in two years; contrasts between highly correlated models have smaller SD and smaller MDE.']
    (out/'POWER.md').write_text('\n'.join(P) + '\n', encoding='utf-8')
    print('\n'.join(L[4:]) + '\n\n' + '\n'.join(P[6:]))


if __name__ == '__main__':
    main()
