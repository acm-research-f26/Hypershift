"""BC review Task 3: regime sensitivity of power (predeclared D5).

  python scripts/bcreview_power.py   -> docs/audit_20261022/A9_POWER_REGIME.md
Dev series (2019-2023, inspected): NL style-residual RankIC of the leak-free residual LightGBM, RR, and their difference.
"""
import sys
from pathlib import Path

import numpy as np
from scipy.stats import nct, norm, t as tdist

sys.path.insert(0, 'src')
sys.path.insert(0, 'scripts')
from hypershift.featbench.data import load_fb  # noqa: E402
from hypershift.fbaudit import stats as S, diag as D, diag2 as D2  # noqa: E402
from fbaudit_refit import corrected_fb  # noqa: E402

COR = Path('results/FBAUDIT_20261022/corrected')
OUT = Path('docs/audit_20261022')
BC_FOLDS, BC_DAYS = 9, 250


def lrv(x):
    return S.pooled({0: x}, 'stationary', 10, 3000)['se'] ** 2 * len(x)


def main():
    ser = {'model': {}, 'RR': {}, 'model − RR': {}}
    for f in S.FOLDS:
        fb = corrected_fb(load_fb(f, 5), f)
        ev = fb.evaluate
        mask = (fb.y_ok[:, ev] & fb.eligible[:, ev]).T
        t_nl = D2.nl_resid(fb.neutral[:, ev].T.astype(np.float64), fb, ev, mask)
        res = np.load(COR / str(f) / 'lgbm_rich_residual_es.npz')['pred'].astype(np.float64)
        a = S.spearman_daily(res, t_nl, mask)
        b = S.spearman_daily(D2.residual_reversal(fb, ev, 21), t_nl, mask)
        ser['model'][f], ser['RR'][f], ser['model − RR'][f] = a, b, a - b
        print('fold', f, flush=True)
    L = ['# A9 — Power and regime sensitivity for Study BC (predeclared D5)', '',
         'Dev 2019–2023 (inspected), leak-free, NL style-residual metric (A7). LRV = per-day long-run variance from a '
         'stationary bootstrap (block 10) within each year. BC = 9 annual folds × about 250 days. Generated by '
         '`scripts/bcreview_power.py`.', '',
         '## Per-year mean and LRV', '', '| Series | ' + ' | '.join(str(f) for f in S.FOLDS) + ' | Max/min LRV |',
         '|---|' + '---|' * (len(S.FOLDS) + 1)]
    summary = {}
    for k, v in ser.items():
        lr = {f: lrv(x) for f, x in v.items()}
        means = np.array([x.mean() for x in v.values()])
        summary[k] = dict(lrv=np.mean(list(lr.values())), lrv_max=max(lr.values()), sd_years=means.std(ddof=1),
                          mean=means.mean(), means=means)
        L.append(f'| {k} | ' + ' | '.join(f'{v[f].mean():+.4f} / {lr[f]:.4f}' for f in S.FOLDS) +
                 f' | {max(lr.values()) / min(lr.values()):.2f} |')
    L += ['', 'Cells show the year mean / LRV.', '',
          '## BC minimum detectable effect under LRV inflation (pooled mean of 9 fold means, 80% power, α .05 two-sided)', '',
          '| Series | Dev LRV | ×1 | ×1.5 | ×2 | ×3 | 8 years at dev mean + 1 year (2008) at 3 × dev max |', '|---|---|---|---|---|---|---|']
    for k, s in summary.items():
        mde = lambda m: 2.8 * np.sqrt(s['lrv'] * m / (BC_FOLDS * BC_DAYS))
        mix = 2.8 * np.sqrt((8 * s['lrv'] + 3 * s['lrv_max']) / BC_FOLDS ** 2 / BC_DAYS)
        L.append(f"| {k} | {s['lrv']:.4f} | {mde(1):.4f} | {mde(1.5):.4f} | {mde(2):.4f} | {mde(3):.4f} | {mix:.4f} |")
    L += ['', '## Year-level inference (t across 9 year means, two-sided α .05)', '',
          'Between-year SD taken from the 5 dev year means (a noisy estimate from 5 numbers). Power from the noncentral t.', '',
          '| Series | Dev mean | Between-year SD | Power at θ = 0.008 | θ = 0.011 | Years needed for 80% at 0.008 |', '|---|---|---|---|---|---|']
    for k, s in summary.items():
        sd = s['sd_years']
        crit = tdist.ppf(.975, BC_FOLDS - 1)
        pw = lambda th, n=BC_FOLDS: 1 - nct.cdf(tdist.ppf(.975, n - 1), n - 1, th / (sd / np.sqrt(n))) + \
            nct.cdf(-tdist.ppf(.975, n - 1), n - 1, th / (sd / np.sqrt(n)))
        need = next((n for n in range(3, 200) if pw(.008, n) >= .8), None)
        L.append(f"| {k} | {s['mean']:+.4f} | {sd:.4f} | {pw(.008):.2f} | {pw(.011):.2f} | {need} |")
    L += ['', '## Leave-one-year-out pooled (dev template for BC)', '', '| Series | ' + ' | '.join(f'drop {f}' for f in S.FOLDS) + ' |',
          '|---|' + '---|' * len(S.FOLDS)]
    for k, s in summary.items():
        m = s['means']
        L.append(f'| {k} | ' + ' | '.join(f'{np.delete(m, i).mean():+.4f}' for i in range(len(m))) + ' |')
    (OUT / 'A9_POWER_REGIME.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
