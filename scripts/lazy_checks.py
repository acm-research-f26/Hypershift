"""Pre-outcome checks P1, P3-P6 of docs/strategy_lazyprices_20261023/PREREG.md (no returns are read).

  SEC_USER_AGENT=... python scripts/lazy_checks.py   -> docs/strategy_lazyprices_20261023/PRECHECKS.md
"""
import csv
import json
import re
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
from hypershift.data import edgar as ED  # noqa: E402
from hypershift.strategy import lazyprices as LP  # noqa: E402

NPZ = 'data/pit/pit_sp500_2016_2023.npz'
OUT = Path('docs/strategy_lazyprices_20261023/PRECHECKS.md')


def signal_rows(cal, labels, path='data/edgar/signals.csv', cmap_path='data/edgar/cik_map.json'):
    """(entity, available_index, similarity, form): a filing of CIK c belongs to entity i if c is the entity's CIK in a
    dated segment and the filing was accepted between 120 days before the segment start and the segment end."""
    cmap = json.loads(Path(cmap_path).read_text())
    by_cik = {}
    for i, lab in enumerate(labels):
        for s, e, c in cmap.get(lab, {}).get('segments', []):
            by_cik.setdefault(int(c), []).append((i, np.datetime64(s) - 120, np.datetime64(e)))
    rows, recs = [], list(csv.DictReader(open(path)))
    for r in recs:
        acc = np.datetime64(r['acceptance_et'])
        a = ED.available_index(acc, cal)
        if a >= len(cal) or r['error']:
            continue
        for i, s, e in by_cik.get(int(r['cik']), []):
            if s <= np.datetime64(acc, 'D') <= e:
                rows.append((i, a, float(r['similarity']), r['form']))
    return rows, recs


def main():
    z = np.load(NPZ)
    labels = list(z['labels'])
    cal = z['dates'].astype('datetime64[D]')
    member, observed = z['member'], z['observed']
    cs = np.pad(np.cumsum(~observed, 1), ((0, 0), (1, 0)))
    hist = np.zeros_like(observed)
    hist[:, 63:] = cs[:, 64:] - cs[:, :-64] == 0
    eligible = hist & member
    rows, recs = signal_rows(cal, labels)
    sim = np.array([float(r['similarity']) for r in recs if not r['error']])
    L = ['# Pre-outcome checks (text and mechanics only; no returns read)', '',
         'Generated by `scripts/lazy_checks.py` from `data/edgar/signals.csv` and the CIK map.', '']

    # P1 timestamps
    sec = ED.SecClient()
    rng = np.random.default_rng(0)
    sample = [recs[k] for k in rng.choice(len(recs), size=min(12, len(recs)), replace=False)]
    ok = 0
    lines = []
    for r in sample:
        a = r['accession']
        x = sec.get(f"https://www.sec.gov/Archives/edgar/data/{int(r['cik'])}/{a.replace('-', '')}/{a}-index.htm").decode('latin-1')
        m = re.search(r'Accepted</div>\s*<div class="info">([^<]+)<', x)
        idx = m.group(1).strip() if m else '?'
        mine = str(np.datetime64(r['acceptance_et'], 's')).replace('T', ' ')
        ok += idx == mine
        lines.append(f'{a}: index {idx} / pipeline {mine}')
    L += [f'**P1 timestamps:** {ok}/{len(sample)} random filings match the index-page "Accepted" time exactly.',
          '', '<details><summary>sample</summary>', ''] + [f'- {x}' for x in lines] + ['', '</details>', '']

    # P3 coverage
    L += ['**P3 signal coverage** (share of eligible members with a valid signal at each monthly formation):', '',
          '| Year | Formations | Mean coverage | Min |', '|---|---|---|---|']
    form_share = []
    for yr in range(2016, 2024):
        Fs = LP.formation_days(cal, np.datetime64(f'{yr}-07-01' if yr == 2016 else f'{yr}-01-01'), np.datetime64(f'{yr}-12-31'))
        cov = []
        for F in Fs:
            s, f = LP.signals_at(rows, len(labels), F, cal)
            e = eligible[:, F - 1]
            cov.append(np.isfinite(s[e]).mean())
            ch = LP.changers(s, f, e)
            form_share.append((str(cal[F])[:7], int(ch.sum()), int((ch & (f == '10-K')).sum()), int(e.sum())))
        L.append(f'| {yr} | {len(Fs)} | {np.mean(cov):.3f} | {np.min(cov):.3f} |')
    L += ['', 'Changers per formation (count, of which 10-K signals, eligible names): '
          + ', '.join(f'{a} {b}/{c}/{d}' for a, b, c, d in form_share[::6]) + ' (every 6th month).', '']

    # P4 extraction and distribution
    ntok = np.array([int(r['n_tokens']) for r in recs])
    small = [(r['accession'], r['form'], r['n_tokens']) for r in recs if int(r['n_tokens']) < 1000]
    errs = [r['accession'] for r in recs if r['error']]
    L += [f'**P4 extraction:** {len(recs)} signal filings; parse errors {len(errs)}; documents under 1,000 tokens: '
          f'{len(small)}' + (': ' + ', '.join(f'{a} ({f}, {n})' for a, f, n in small[:15]) if small else '') + '.',
          f'Token counts: median {int(np.median(ntok))}, 5th pct {int(np.percentile(ntok, 5))}.', '',
          '| Year | Form | N | Mean sim | SD | p10 | p50 | p90 |', '|---|---|---|---|---|---|---|---|']
    yrs = np.array([r['acceptance_et'][:4] for r in recs])
    forms = np.array([r['form'] for r in recs])
    simall = np.array([float(r['similarity']) for r in recs])
    for yr in sorted(set(yrs)):
        for f in ('10-K', '10-Q'):
            m = (yrs == yr) & (forms == f)
            if m.any():
                q = np.percentile(simall[m], [10, 50, 90])
                L.append(f'| {yr} | {f} | {m.sum()} | {simall[m].mean():.3f} | {simall[m].std():.3f} | {q[0]:.3f} | {q[1]:.3f} | {q[2]:.3f} |')

    # P5 first inline XBRL
    ix = np.array([int(r['inline_xbrl']) == 1 and int(r['prior_inline_xbrl']) == 0 for r in recs])
    sd = simall.std()
    gap = (simall[ix].mean() - simall[~ix].mean()) / sd if ix.any() else float('nan')
    L += ['', f'**P5 inline-XBRL transition:** first inline-XBRL filings (prior not inline) N = {ix.sum()}, mean '
          f'similarity {simall[ix].mean():.3f} vs {simall[~ix].mean():.3f} for the rest: difference {gap:+.2f} SD '
          f'(pass if within ±1 SD). Share of first-iXBRL filings among bottom-quintile similarity: '
          f'{(ix & (simall <= np.percentile(simall, 20))).sum() / max((simall <= np.percentile(simall, 20)).sum(), 1):.3f} '
          f'vs {ix.mean():.3f} overall.']

    # P6 length artefact
    dl = np.abs(np.log(np.maximum(ntok, 1)) - np.log(np.maximum(np.array([int(r['n_tokens_prior']) for r in recs]), 1)))
    c = np.corrcoef(simall, dl)[0, 1]
    L += ['', f'**P6 length:** corr(similarity, |Δ log tokens|) = {c:+.3f} (fix before scoring if below −0.8).']
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
