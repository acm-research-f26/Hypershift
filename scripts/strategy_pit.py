"""Predeclared PIT kill test of the style-only book (docs/strategy_pit_20261023/PREREG.md).

  python scripts/strategy_pit.py        -> docs/strategy_pit_20261023/STYLE_PIT.md
Scores are cached in results/STRATEGY_PIT_20261023/ (git-ignored) so the report can be regenerated without retraining.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
from hypershift.strategy import pit as SP, pit_engine as PE, engine as EN, study as ST, factors as FA, signals as SG  # noqa: E402

RES = Path('results/STRATEGY_PIT_20261023')
OUT = Path('docs/strategy_pit_20261023/STYLE_PIT.md')
MAT = Path('results/FBAUDIT_20261022/matched')
SURV = 'data/fresh/sp500_daily/screen_sp500_2015_2026.npz'


def cached(name, fn):
    p = RES / f'scores_{name}.npz'
    if p.exists():
        z = np.load(p)
        return {int(k): z['s'][i] for i, k in enumerate(z['days'])}
    sc = fn()
    days = sorted(sc)
    RES.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(p, days=np.array(days), s=np.array([sc[k] for k in days]))
    return sc


def rr21_scores(d):
    return {int(s) + 1: SG.rr21(d.price, d.observed, d.beta, d.sectors, d.eligible, int(s))
            for s in SP.signal_days(d.dates)}


def random_scores(d):
    rng = np.random.default_rng(0)
    return {int(s) + 1: np.where(d.eligible[:, s], rng.normal(size=len(d.sectors)), np.nan) for s in SP.signal_days(d.dates)}


def saved_survivor_scores(d):
    """Arm O: survivor-trained FBAUDIT style_residual predictions (seeds 7/19/42, rank-averaged), mapped to entities."""
    z = np.load(SURV)
    n_surv = int(z['identity_ok'].sum())
    ent = np.full(n_surv, -1)
    surv_ix = np.load(SP.NPZ)['survivor_index']
    for i, j in enumerate(surv_ix):
        if j >= 0:
            ent[j] = i
    idx = {str(x): i for i, x in enumerate(d.dates.astype(str))}
    sc = {}
    for f in (2019, 2020, 2021, 2022, 2023):
        P = [np.load(MAT / str(f) / f'style_residual_s{s}.npz') for s in (7, 19, 42)]
        pred = np.mean([np.argsort(np.argsort(p['pred'], 1), 1) for p in P], 0)
        for k, day in enumerate(P[0]['dates']):
            if k % 5 == 0 and str(day) in idx and idx[str(day)] + 1 < len(d.dates):
                row = np.full(len(d.sectors), np.nan)
                ok = ent >= 0
                row[ent[ok]] = pred[k][ok]
                sc[idx[str(day)] + 1] = row
    return sc


def legs(res, w_sign):
    c = res['w_start'] * res['r']
    return (np.where(res['w_start'] > 0, c, 0).sum(1) * 252).mean(), (np.where(res['w_start'] < 0, c, 0).sum(1) * 252).mean()


def main():
    d, fb = SP.load()
    ff = FA.load_ff('data/factors')
    end = len(d.dates) - 1
    arms = {'P': cached('P', lambda: SP.annual_scores(fb, 'lgbm')),
            'R': cached('R', lambda: SP.annual_scores(fb, 'ridge')),
            'RR21': cached('RR21', lambda: rr21_scores(d)),
            'N': cached('N', lambda: random_scores(d))}
    dS, fbS = SP.restrict(d, fb, d.survivor)
    arms['S'] = cached('S', lambda: SP.annual_scores(fbS, 'lgbm'))
    arms['O'] = cached('O', lambda: saved_survivor_scores(d))
    data_for = {k: (dS if k == 'S' else d) for k in arms}
    runs = {k: PE.run_pit(sc, data_for[k], mode='LS', top=.1, band=.3, cost_bp=0, borrow_bp=50, end=end, trace=True)
            for k, sc in arms.items()}
    yrs = {k: len(r['net']) / 252 for k, r in runs.items()}
    L = ['# D. Style-only book on a point-in-time S&P 500 universe (predeclared kill test)', '',
         'Spec: `PREREG.md` (committed before these numbers). Data: `PIT_DATA.md`. Generated by `scripts/strategy_pit.py`.',
         'LS book: sector-neutral 10%/30% band, beta-hedged, weekly, next-open, borrow 50 bp/yr; PIT engine '
         '(`strategy/pit_engine.py`). Window 2018-01-02..2023-12-29 (arm O: 2019–2023).', '',
         '## Arms', '',
         '| Arm | Net Sharpe @5 | @10 [95% CI] | @20 | @30 | Ann. net @10 | Max DD | Worst year | Traded/yr | FF alpha @10 (t) | R² | Long leg ann. | Short leg ann. |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    stats = {}
    for k, r in runs.items():
        s = {c: ST.ir_stats(ST.net(r, c)) for c in (5, 10, 20, 30)}
        a = FA.attribute(ST.net(r, 10), r['dates'], ff)
        worst = min(ST.per_year(ST.net(r, 10), r['dates']).values())
        lg, sh = legs(r, None)
        stats[k] = (s, a)
        L.append(f"| {k} | {s[5]['ir']:+.2f} | {s[10]['ir']:+.2f} [{s[10]['ci'][0]:+.2f}, {s[10]['ci'][1]:+.2f}] | "
                 f"{s[20]['ir']:+.2f} | {s[30]['ir']:+.2f} | {s[10]['ann_mean']:+.3f} | {s[10]['mdd']:+.3f} | {worst:+.3f} | "
                 f"{r['traded'].sum() / yrs[k]:.1f} | {a['alpha_ann']:+.3f} ({a['t']:+.2f}) | {a['r2']:.2f} | {lg:+.3f} | {sh:+.3f} |")
        print(k, f"{s[10]['ir']:+.2f}", flush=True)
    L += ['', 'Leg columns: annualised gross contribution of positive / negative weights (hedge basket included in the '
          'leg its weight sign falls in); open-execution split ignored.', '']

    # per year
    L += ['## Per-year net return @10 bp', '', '| Arm | ' + ' | '.join(str(y) for y in range(2018, 2024)) + ' |',
          '|---|' + '---|' * 6]
    for k, r in runs.items():
        py = ST.per_year(ST.net(r, 10), r['dates'])
        L.append(f'| {k} | ' + ' | '.join(f"{py[y]:+.3f}" if y in py else '–' for y in range(2018, 2024)) + ' |')

    # paired
    L += ['', '## Paired contrasts (daily net @10 bp, same days)', '', '| Contrast | Ann. mean | Sharpe of difference [95% CI] |', '|---|---|---|']
    for a_, b_ in (('P', 'R'), ('P', 'S'), ('P', 'RR21')):
        x = ST.net(runs[a_], 10) - ST.net(runs[b_], 10)
        s = ST.ir_stats(x)
        L.append(f"| {a_} − {b_} | {s['ann_mean']:+.3f} | {s['ir']:+.2f} [{s['ci'][0]:+.2f}, {s['ci'][1]:+.2f}] |")
    po = np.isin(runs['P']['dates'], runs['O']['dates'])
    x = ST.net(runs['P'], 10)[po] - ST.net(runs['O'], 10)
    s = ST.ir_stats(x)
    L.append(f"| P − O (2019–2023) | {s['ann_mean']:+.3f} | {s['ir']:+.2f} [{s['ci'][0]:+.2f}, {s['ci'][1]:+.2f}] |")

    # sensitivities for P
    L += ['', '## Sensitivities (arm P, net Sharpe @10 bp)', '', '| Variant | Net Sharpe [95% CI] | Note |', '|---|---|---|']
    fail = d.failure.astype(float)
    for name, kw, note in (('next-close execution', dict(execution='close'), ''),
                           ('failure delistings −100%', dict(terminal=-1. * fail), f'{int(d.failure.sum())} entities flagged'),
                           ('failure delistings −30%', dict(terminal=-.3 * fail), 'Shumway-style')):
        r = PE.run_pit(arms['P'], d, mode='LS', top=.1, band=.3, cost_bp=0, borrow_bp=50, end=end, **kw)
        s = ST.ir_stats(ST.net(r, 10))
        L.append(f"| {name} | {s['ir']:+.2f} [{s['ci'][0]:+.2f}, {s['ci'][1]:+.2f}] | {note} |")
    dl = runs['P']['delisted_weight']
    L.append(f'| (delisting events in P) | {int((dl > 0).sum())} days, total |weight| {dl.sum():.3f} | liquidated at last close |')

    # sanity
    L += ['', '## Sanity checks', '']
    bench = PE.benchmark_ew(arms['P'], d, cost_bp=10, end=end)
    for lbl, m in (('2018–2023', slice(None)), ('2019–2023', bench['dates'] >= np.datetime64('2019-01-01'))):
        a = FA.attribute(bench['net'][m], bench['dates'][m], ff, excess=True)
        L.append(f"- **E1** PIT equal-weight benchmark ({lbl}, weekly, 10 bp), FF alpha {a['alpha_ann']:+.3f} (t {a['t']:+.2f}); "
                 'survivor panel 2019–2023 gave +3.1% (t 2.6).')
    s = stats['N'][0][10]
    drag = (runs['N']['traded'].sum() * 10e-4 + runs['N']['borrow'].sum()) / yrs['N']
    L.append(f"- **E5** random scores: net Sharpe {s['ir']:+.2f} [{s['ci'][0]:+.2f}, {s['ci'][1]:+.2f}], ann. net {s['ann_mean']:+.3f}; "
             f'cost + borrow drag {drag:.3f}/yr.')
    for k in ('P', 'O'):
        old = EN.run(arms[k], d, mode='LS', top=.1, band=.3, cost_bp=0, borrow_bp=50, end=end)
        so = ST.ir_stats(ST.net(old, 10))
        L.append(f"- **E6** arm {k}: frozen `engine.run` (stuck weights) net Sharpe {so['ir']:+.2f} vs `run_pit` "
                 f"{stats[k][0][10]['ir']:+.2f}.")
    L.append('- **E4** label-maturity guard: `pit.train_signals` raises if any training label matures after the as-of '
             'signal (`test_train_signals_only_matured_and_pit_eligible`).')

    # decision
    s, a = stats['P']
    pr = ST.net(runs['P'], 10) - ST.net(runs['R'], 10)
    sh = s[10]['ir']
    if sh < .3:
        dec = 'STOP'
    elif sh >= .6 and a['t'] >= 1.5 and pr.mean() >= 0:
        dec = 'CONTINUE (ask the user to authorise long-history data; not validation)'
    else:
        dec = 'INCONCLUSIVE → DEFER'
    L += ['', '## Predeclared decision (arm P)', '',
          f"Net Sharpe @10 bp {sh:+.2f}; FF alpha t {a['t']:+.2f}; mean daily P − R {pr.mean() * 252:+.3f}/yr → **{dec}**."]
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
