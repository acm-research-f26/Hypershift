"""EAR pre-outcome feasibility (no return after any signal's availability is read).

  python scripts/ear_checks.py   -> docs/strategy_ear_20261023/FEASIBILITY.md
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
sys.path.insert(0, 'scripts')
from hypershift.strategy import pit as SP  # noqa: E402
from ear_common import signal_rows, targets, eligibility  # noqa: E402

OUT = Path('docs/strategy_ear_20261023/FEASIBILITY.md')


def main():
    d, _ = SP.load()
    assert d.dates.max() <= np.datetime64('2023-12-31')
    rows = {'EAR': signal_rows(d, (-1, 1)), 'control': signal_rows(d, (-4, -2))}
    tg = {k: targets(d, r) for k, r in rows.items()}
    Fs = sorted(tg['EAR'])
    yrs = d.dates[np.array(Fs)].astype('datetime64[Y]').astype(int) + 1970
    L = ['# EAR pre-outcome feasibility (no post-signal return read)', '',
         'Generated by `scripts/ear_checks.py`. Signals: market-adjusted return over d0−1..d0+1 (EAR) and over '
         'd0−4..d0−2 (matched control), both usable from the open after d0+1; each event binned at availability '
         'against trailing-252-day 20th/80th percentiles; four-month validity; FF12-neutral tilt capped at 2× B '
         '(`ear.event_bins`, `ear.tilt_weights`).', '',
         f"- Events with a computable EAR: {np.isfinite([r[2] for r in rows['EAR']]).sum()} of {len(rows['EAR'])}; "
         f"control computable: {np.isfinite([r[2] for r in rows['control']]).sum()}.",
         f"- IR splice excluded: entity IR ineligible before 2020-03-03 ({int((d.eligible & ~eligibility(d)).sum())} "
         'stock-days).', '',
         '| Year | Formations | EAR signal coverage (mean, min) | Bottom/top names (median) | EAR overlay turnover / yr | Control overlay turnover / yr | Bin overlap EAR vs control |',
         '|---|---|---|---|---|---|---|']
    for y in np.unique(yrs):
        Fy = [F for F, yy in zip(Fs, yrs) if yy == y]
        cov = [tg['EAR'][F][4] for F in Fy]
        nb = [int(tg['EAR'][F][2].sum()) for F in Fy]
        tv = {}
        for k in tg:
            prev = None
            s = 0.
            for F in Fy:
                act = tg[k][F][1] - tg[k][F][0]
                if prev is not None:
                    s += np.abs(act - prev).sum()
                prev = act
            tv[k] = s * 12 / max(len(Fy) - 1, 1)
        ov = np.mean([((tg['EAR'][F][2] & tg['control'][F][2]).sum() + (tg['EAR'][F][3] & tg['control'][F][3]).sum())
                      / max(tg['EAR'][F][2].sum() + tg['EAR'][F][3].sum(), 1) for F in Fy])
        L.append(f'| {y} | {len(Fy)} | {np.mean(cov):.3f}, {np.min(cov):.3f} | {int(np.median(nb))} | '
                 f"{tv['EAR']:.2f} | {tv['control']:.2f} | {ov:.3f} |")
    mx = max(float((tg['EAR'][F][1] - tg['EAR'][F][0]).max()) for F in Fs)
    L += ['', f'- Maximum active weight {mx:.4f} (B weight about 0.002 per name).',
          '- Turnover column: Σ|Δ active weight| between consecutive formations, annualised, before drift (the '
          'engine measures the realised figure).']
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
