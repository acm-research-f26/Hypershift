"""WP-A exploration (2016-02..2023-12; years inspected before; survivor universe): exploratory evidence only.

  python scripts/strategy_explore.py   -> docs/strategy_20261022/EXPLORE.md
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
from hypershift.strategy import study as ST, factors as FA  # noqa: E402

OUT = Path('docs/strategy_20261022/EXPLORE.md')
START, END = np.datetime64('2016-02-01'), np.datetime64('2023-12-31')


def fmt_ci(s):
    return f"{s['ir']:+.2f} [{s['ci'][0]:+.2f}, {s['ci'][1]:+.2f}]"


def main():
    d = ST.load_data()
    ff = FA.load_ff('data/factors')
    L = ['# WP-A exploration: PRICE3 and comparators, 2016-02 to 2023-12', '',
         '**Status: exploratory.** Every year here had been inspected by earlier HyperShift studies. The universe is '
         '462 *current* S&P 500 constituents (survivor-conditioned), so **nothing here is a historically investable '
         'backtest**. Candidate, rules and thresholds were predeclared in '
         '`docs/superpowers/plans/2026-10-22-strategy.md` (commit fdca968) before any number was computed. '
         'Generated by `scripts/strategy_explore.py`.', '',
         '**Construction.**',
         '- Monthly rebalance; signals at the previous close; trades at the **next open**; weights drift between trades.',
         '- **LO:** equal-weight top 20%, with a 40% hold band.',
         '- **Benchmark:** equal weight of eligible stocks, on the same days, with the same costs.',
         '- **LS:** sector-neutral top/bottom 20% (0.5 gross per leg), beta-hedged with an equal-weight basket; borrow 50 bp/yr.',
         '- **Costs:** c bp per unit traded (two-sided traded notional / NAV).', '']
    for execution in ('open', 'close'):
        res = ST.run_all(d, START, END, execution=execution)
        years = len(res['BENCH']['net']) / 252
        L += [f'## Execution: next {execution}', '',
              '| Portfolio | Ann. net return (10 bp) | Net Sharpe (10 bp) | Traded / yr | Active vs EW: ann. mean (10 bp) | Active IR @5 | @10 [95% CI] | @20 | @30 | Active max DD (10 bp) |',
              '|---|---|---|---|---|---|---|---|---|---|']
        bnet = {c: ST.net(res['BENCH'], c) for c in ST.COSTS}
        rows = {}
        for k, r in res.items():
            n10 = ST.net(r, 10)
            s = ST.ir_stats(n10)
            tr = r['traded'].sum() / years
            if k.endswith('-LO'):
                act = {c: ST.net(r, c) - bnet[c] for c in ST.COSTS}
                a = {c: ST.ir_stats(act[c]) for c in ST.COSTS}
                rows[k] = (act, a, tr)
                L.append(f"| {k} | {s['ann_mean']:+.3f} | {s['ir']:+.2f} | {tr:.2f} | {a[10]['ann_mean']:+.3f} | {a[5]['ir']:+.2f} | "
                         f"{fmt_ci(a[10])} | {a[20]['ir']:+.2f} | {a[30]['ir']:+.2f} | {a[10]['mdd']:+.3f} |")
            else:
                L.append(f"| {k} | {s['ann_mean']:+.3f} | {fmt_ci(s)} | {tr:.2f} | — | — | — | — | — | {s['mdd']:+.3f} (net) |")
        # attribution
        L += ['', f'### Factor attribution (daily, FF5 + MOM + ST_Rev, Newey–West 10 lags; 10 bp; next {execution})', '',
              '| Series | Alpha ann. | t | Mkt-RF | SMB | HML | RMW | CMA | MOM | STREV | R² |', '|---|---|---|---|---|---|---|---|---|---|---|']
        attrs = {}
        for name, series in [(f'{k} active', rows[k][0][10]) for k in rows] + [('PRICE3-LS net', ST.net(res['PRICE3-LS'], 10)),
                                                                               ('BENCH excess', bnet[10])]:
            at = FA.attribute(series, res['BENCH']['dates'], ff, excess=name.startswith('BENCH'))
            attrs[name] = at
            b = at['betas']
            L.append(f"| {name} | {at['alpha_ann']:+.3f} | {at['t']:+.2f} | " + ' | '.join(f'{b[f]:+.2f}' for f in FA.FACTORS) + f" | {at['r2']:.2f} |")
        # per-year active
        L += ['', f'### Per-year active return vs EW (10 bp; next {execution})', '',
              '| Portfolio | ' + ' | '.join(str(y) for y in sorted(ST.per_year(bnet[10], res['BENCH']['dates']))) + ' |',
              '|---|' + '---|' * len(ST.per_year(bnet[10], res['BENCH']['dates']))]
        for k in rows:
            py = ST.per_year(rows[k][0][10], res['BENCH']['dates'])
            L.append(f'| {k} | ' + ' | '.join(f'{v:+.3f}' for v in py.values()) + ' |')
        pl = ST.per_year(ST.net(res['PRICE3-LS'], 10), res['BENCH']['dates'])
        L.append('| PRICE3-LS (net) | ' + ' | '.join(f'{v:+.3f}' for v in pl.values()) + ' |')
        if execution == 'open':
            act, a, tr = rows['PRICE3-LO']
            worst = min(ST.per_year(act[10], res['BENCH']['dates']).values())
            go, checks = ST.decision(a[10]['ir'], attrs['PRICE3-LO active']['alpha_ann'], a[20]['ir'], worst, tr)
            ls = ST.ir_stats(ST.net(res['PRICE3-LS'], 10))
            ls_go = ls['ir'] >= .5 and attrs['PRICE3-LS net']['alpha_ann'] >= 0
            primary = (go, checks, a[10]['ir'], ls, ls_go, attrs)
            yrs_needed = (2.8 / a[10]['ir']) ** 2 if a[10]['ir'] > 0 else float('inf')
    # PIT membership sensitivity (open execution)
    pe = ST.pit_eligible(d)
    rp = ST.run_all(d, START, END, execution='open', eligible=pe)
    act_p = ST.net(rp['PRICE3-LO'], 10) - ST.net(rp['BENCH'], 10)
    sp = ST.ir_stats(act_p)
    # capacity (descriptive, adjusted-price dollar volume; level bias irrelevant at this precision)
    dv = d.close * d.volume
    n_hold = int(round(.2 * np.mean([d.eligible[:, r - 1].sum() for r in ST.scores_for(d, 'PRICE3', START, END)])))
    adv = np.array([np.nanmedian(dv[:, max(0, r - 21):r], 1) for r in list(ST.scores_for(d, 'PRICE3', START, END))[::6]])
    low_adv = np.nanpercentile(adv[adv > 0], 1)
    go, checks, ir10, ls, ls_go, attrs = primary
    L += ['', '## PIT-membership sensitivity (eligible only while an S&P 500 member on the date; next open, 10 bp)', '',
          f"PRICE3-LO active vs EW (same filter): ann. {sp['ann_mean']:+.3f}, IR {fmt_ci(sp)}. Survivors only: stocks "
          'that later left the index are still missing.', '',
          '## Capacity (descriptive)', '',
          f'About {n_hold} holdings. At $10M AUM a full position is about ${10e6 / n_hold:,.0f}; at $100M about ${100e6 / n_hold:,.0f}. '
          f'The 1st-percentile 20-day median dollar volume across the universe is about ${low_adv:,.0f}, so at $100M a full position '
          f'is ≤ {100e6 / n_hold / low_adv:.1%} of one day\'s volume for the least liquid names. Capacity is not the binding constraint '
          'for an S&P 500 universe at these sizes.', '',
          '## Power', '',
          f'Observed PRICE3-LO active IR (10 bp, open) {ir10:+.2f}. Years of data needed to detect an IR of that size at 80% power '
          f'(two-sided α 0.05; IR SE ≈ 1/√years): **{yrs_needed:.0f}**. The 7.9 years here cannot confirm it.', '',
          '## Predeclared exploration decision (PRICE3-LO, 10 bp, next open)', '',
          '| Check | Pass |', '|---|---|'] + [f'| {k} | {"yes" if v else "no"} |' for k, v in checks.items()] + \
         ['', f"**PRICE3-LO: {'GO (freeze for paper trading)' if go else 'NOT GO'}**. "
              f"PRICE3-LS: net Sharpe {fmt_ci(ls)}, alpha {attrs['PRICE3-LS net']['alpha_ann']:+.3f}, "
              f"**{'GO' if ls_go else 'NOT GO'}**."]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
