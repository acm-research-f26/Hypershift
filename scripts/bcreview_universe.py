"""BC review Task 4: historical-universe integrity without prices.

  python scripts/bcreview_universe.py   -> docs/audit_20261022/A10_UNIVERSE.md
Source: fja05680/sp500 point-in-time membership (data/audit/membership/, sha256 recorded in the doc). No prices used.
"""
import csv
import hashlib
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

MEM = Path('data/audit/membership')
OUT = Path('docs/audit_20261022')
PANEL = 'data/fresh/sp500_daily/screen_sp500_2015_2026.npz'


def norm(t):
    return t.strip().upper().replace('.', '-')


def main():
    z = np.load(PANEL)
    ours = [norm(str(t)) for t in z['tickers'][z['identity_ok'].astype(bool)]]
    our = set(ours)
    rows = list(csv.DictReader(open(MEM / 'components.csv', encoding='utf-8')))
    snap = {r['date']: {norm(t) for t in r['tickers'].split(',')} for r in rows}
    dates = sorted(snap)
    intervals = defaultdict(list)
    for r in csv.DictReader(open(MEM / 'ticker_start_end.csv', encoding='utf-8')):
        intervals[norm(r['ticker'])].append((r['start_date'], r['end_date'] or '9999'))
    sha = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in (MEM / 'components.csv', MEM / 'ticker_start_end.csv')}
    L = ['# A10 — Historical-universe integrity for Study BC (no prices used)', '',
         'Source: point-in-time S&P 500 membership from github.com/fja05680/sp500 (`S&P 500 Historical Components & '
         'Changes (Updated).csv`, `sp500_ticker_start_end.csv`), downloaded 2026-10-22, sha256 ' +
         ', '.join(f'`{k}` {v[:16]}…' for k, v in sha.items()) + '.',
         '',
         '**Source caveats (stated by its author):**',
         '- built from a book download plus Wikipedia "selected changes" and manual searches;',
         '- the first years may miss symbols;',
         '- symbols are those used *at the time*, so renamed companies appear under old symbols.', '',
         'Generated by `scripts/bcreview_universe.py`.', '',
         '## Cohort sizes on 1 July of each BC year', '',
         '- **Index members** = point-in-time S&P 500 on the first listed date ≥ 1 July.',
         '- **C2** = members that are also among the 462 current-constituent survivors (direct symbol match after '
         'normalising "." to "-").',
         '- **Survivor share** = C2 / members: the fraction of the historical index the backcast can see. This is a '
         '**lower bound**: members that later renamed are not matched by symbol, which also inflates the last column.', '',
         '| Year | Index members | C2 (members ∩ our 462) | Survivor share | Our 462 not members that day |',
         '|---|---|---|---|---|']
    for y in range(2004, 2013):
        d = next(x for x in dates if x >= f'{y}-07-01')
        m = snap[d]
        c2 = m & our
        L.append(f'| {y} ({d}) | {len(m)} | {len(c2)} | {len(c2) / len(m):.0%} | {len(our - m)} |')
    # identity checks
    reused = []
    for t in ours:
        iv = sorted(intervals.get(t, []))
        for (s1, e1), (s2, e2) in zip(iv, iv[1:]):
            if e1 != '9999' and s2 > e1 and (np.datetime64(s2) - np.datetime64(e1)).astype(int) > 365:
                reused.append(f'{t} ({s1}..{e1}; {s2}..{e2 if e2 != "9999" else "now"})')
    first = {t: min((s for s, _ in intervals.get(t, [])), default=None) for t in ours}
    never = [t for t in ours if first[t] is None]
    late = sorted([t for t in ours if first[t] and first[t] > '2012-12-31'])
    early = [t for t in ours if first[t] and first[t] <= '2004-07-01']
    L += ['', '## Ticker identity', '',
          f'- Our tickers with no interval in the membership file: {len(never)} '
          f'({", ".join(never[:20])}{" …" if len(never) > 20 else ""}). Likely symbol changes or class-share notation.',
          f'- Our tickers first in the index after 2012 (pre-inclusion names in BC, or renamed): {len(late)} of 462.',
          f'- Our tickers first in the index on or before 2004-07-01: {len(early)}.',
          f'- Symbols with a gap of more than 1 year between index intervals (a mix of re-entries by the same '
          f'company, e.g. AMD, DD, PCG, TER, and **possible symbol reuse by a different company**, e.g. BR, AMP, CNC; '
          f'point-in-time matching by symbol is unsafe for the earlier interval): {len(reused)}: ' +
          ('; '.join(reused[:25]) if reused else 'none') + ('' if len(reused) <= 25 else ' …'), '',
          '## Limits that cannot be removed with free data', '',
          '- **No delisting returns.** Stocks that left the index or failed are absent: survivor share above.',
          '- **Renamed companies** need a symbol-history map. Without it, C2 under-counts members that later renamed.',
          '- **yfinance history under a current symbol** belongs to the current listing entity and its predecessor, as '
          'Yahoo maps it. Spin-offs and mergers can splice histories; this cannot be audited without a corporate-action '
          'database.',
          '- **Index weights and float** are not available.']
    (OUT / 'A10_UNIVERSE.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
