"""Post-hoc sensitivity (not predeclared, non-gating): the PREREG sector rule assigns every name by return
correlation (73% agreement with GICS on survivors). Re-run arms P, S and O with current GICS for survivors and the
proxy only for non-survivors, to see whether the STOP depends on the sector rule.

  python scripts/strategy_pit_sector_check.py   -> appended to docs/strategy_pit_20261023/STYLE_PIT.md
"""
import sys
from pathlib import Path
from types import SimpleNamespace

import numpy as np

sys.path.insert(0, 'src')
sys.path.insert(0, 'scripts')
from hypershift.strategy import pit as SP, pit_engine as PE, study as ST, factors as FA  # noqa: E402
from strategy_pit import saved_survivor_scores  # noqa: E402

OUT = Path('docs/strategy_pit_20261023/STYLE_PIT.md')


def main():
    d, fb = SP.load()
    ref = np.load(SP.NPZ)['gics_ref']
    mixed = np.where(ref >= 0, ref, d.sectors)
    d = SimpleNamespace(**{**vars(d), 'sectors': mixed})
    fb = SimpleNamespace(**{**vars(fb), 'sectors': mixed})
    ff = FA.load_ff('data/factors')
    dS, fbS = SP.restrict(d, fb, d.survivor)
    arms = {'P': (SP.annual_scores(fb, 'lgbm'), d), 'S': (SP.annual_scores(fbS, 'lgbm'), dS),
            'O': (saved_survivor_scores(d), d)}
    L = ['', '## Post-hoc sensitivity: sector rule (not predeclared; does not change the decision rule)', '',
         'GICS (current) for the 430 matched survivors, return-correlation proxy only for non-survivors. '
         'Generated by `scripts/strategy_pit_sector_check.py`.', '',
         '| Arm | Net Sharpe @10 [95% CI] | @20 | FF alpha @10 (t) | Traded/yr |', '|---|---|---|---|---|']
    for k, (sc, dd) in arms.items():
        r = PE.run_pit(sc, dd, mode='LS', top=.1, band=.3, cost_bp=0, borrow_bp=50, end=len(d.dates) - 1)
        s10, s20 = ST.ir_stats(ST.net(r, 10)), ST.ir_stats(ST.net(r, 20))
        a = FA.attribute(ST.net(r, 10), r['dates'], ff)
        L.append(f"| {k} | {s10['ir']:+.2f} [{s10['ci'][0]:+.2f}, {s10['ci'][1]:+.2f}] | {s20['ir']:+.2f} | "
                 f"{a['alpha_ann']:+.3f} ({a['t']:+.2f}) | {r['traded'].sum() / (len(r['net']) / 252):.1f} |")
        print(L[-1], flush=True)
    with open(OUT, 'a', encoding='utf-8') as fh:
        fh.write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
