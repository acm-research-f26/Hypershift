"""FB audit follow-up (plan amendment, ledgered): is the neutral-target gain more than tilt removal?

  python scripts/fbaudit_followup.py   -> docs/audit_20261022/A4b_NEUTRAL_TARGET.md
Applies the A2 (ex-ante neutralisation, execution lag) and A3 (portfolio) diagnostics to the A4 refit predictions of
models trained on the evaluation target itself. Exploratory: the ladder idea came from inspecting FB results.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
from hypershift.featbench.data import load_fb, OHLCV, PANEL  # noqa: E402
from hypershift.featbench.portfolio import weights_rule, simulate  # noqa: E402
from hypershift.fbaudit import stats as S, diag as D  # noqa: E402

RES = Path('results/FBAUDIT_20261022/main')
FB_ROOT = Path('results/FEATBENCH_SP500_20261022')
OUT = Path('docs/audit_20261022')
ARMS = {'lgbm neutral r50': ('refit', 'lgbm_rich_neutral_r50'), 'lgbm residual r50': ('refit', 'lgbm_rich_residual_r50'),
        'lgbm sector_beta r50': ('refit', 'lgbm_rich_sector_beta_r50'), 'lgbm raw r50': ('refit', 'lgbm_rich_raw_r50'),
        'ridge neutral': ('refit', 'ridge_rich_neutral_sel'), 'ridge raw': ('fb', 'ridge:rich'),
        'reversal16': ('fb', 'block:reversal16')}


def pred(src, name, f):
    if src == 'refit':
        return np.load(RES / str(f) / f'{name}.npz')['pred'].astype(np.float64)
    return S.load_pred(FB_ROOT, f, name)['prediction'].astype(np.float64)


def main():
    o = np.load(OHLCV); z = np.load(PANEL)
    ohlcv_all = o['ohlcv'][z['identity_ok'].astype(bool)].astype(np.float64)
    ser, r2, port = {}, {}, {}
    for f in S.FOLDS:
        fb = load_fb(f, 5)
        ev = fb.evaluate
        ex = D.exposures(fb, ev, 'full')
        mask = (fb.y_ok[:, ev] & fb.eligible[:, ev]).T
        neutral = fb.neutral[:, ev].T.astype(np.float64)
        neu1, _, ok1, keep = D.shifted_neutral(fb, ev, 'close1', ohlcv_all[:, :fb.price.shape[1]])
        for a, (src, name) in ARMS.items():
            p = pred(src, name, f)
            put = lambda v, s: ser.setdefault((a, v), {}).__setitem__(f, s)
            put('base', S.spearman_daily(p, neutral, mask))
            put('neut_full', S.spearman_daily(D.neutralise_pred(p, ex, mask), neutral, mask))
            put('same_kept', S.spearman_daily(p[keep], neutral[keep], mask[keep]))
            put('close1', S.spearman_daily(p[keep], neu1[keep], ok1[keep]))
            r2.setdefault(a, []).append(float(np.nanmean(D.style_r2(p, ex, mask))))
            if a in ('lgbm neutral r50', 'ridge neutral', 'lgbm residual r50'):
                for rule in ('B_sector_ls', 'D_beta_ls'):
                    W = weights_rule(p, fb, ev, rule)
                    g, n = simulate(W, fb, ev, cost=0.), simulate(W, fb, ev, cost=.001)
                    c = port.setdefault((a, rule), {'g': [], 'n': [], 't': []})
                    c['g'].append(g['net']); c['n'].append(n['net']); c['t'].append((g['net'] - n['net']) / .001)
        print('fold', f, flush=True)
    P = lambda a, v: S.pooled(ser[(a, v)], 'stationary', 10)
    Dd = lambda a, va, b, vb: S.pooled({f: ser[(a, va)][f] - ser[(b, vb)][f] for f in S.FOLDS}, 'stationary', 10)
    fmt = lambda r: f"{r['pooled']:+.4f} [{r['ci95'][0]:+.4f}, {r['ci95'][1]:+.4f}]"
    folds = lambda r: ' / '.join(f'{v:+.4f}' for v in r['per_fold'].values())
    L = ['# A4b — Training on the evaluation target: more than tilt removal? (audit follow-up, exploratory)', '',
         'Plan amendment (ledgered): the A4 ladder showed models trained on the factor-neutral evaluation target itself '
         '(`neutral` = 5-day return − beta × equal-weight market, sector-demeaned) score about twice the residual target. '
         'This file applies the A2 neutralisation and lag diagnostics and the A3 portfolio diagnostics to those '
         'predictions. Generated by `scripts/fbaudit_followup.py`.', '',
         '## Scores', '', '| Arm | Neutral RankIC | Neutralised ex ante (full) | Same-close (kept) | close1 | Retained | Style R² |',
         '|---|---|---|---|---|---|---|']
    for a in ARMS:
        s, c = P(a, 'same_kept'), P(a, 'close1')
        ret = f"{c['pooled'] / s['pooled']:.0%}" if s['pooled'] > 0 else 'n/a'
        L.append(f"| {a} | {fmt(P(a, 'base'))} | {fmt(P(a, 'neut_full'))} | {fmt(s)} | {fmt(c)} | {ret} | {np.mean(r2[a]):.3f} |")
    L += ['', '## Contrasts', '', '| Contrast | Pooled [95% CI] | Fold means |', '|---|---|---|']
    for lbl, args in (('lgbm neutral − lgbm raw', ('lgbm neutral r50', 'base', 'lgbm raw r50', 'base')),
                      ('lgbm neutral − lgbm raw neutralised ex ante', ('lgbm neutral r50', 'base', 'lgbm raw r50', 'neut_full')),
                      ('lgbm neutral neutralised − lgbm raw neutralised', ('lgbm neutral r50', 'neut_full', 'lgbm raw r50', 'neut_full')),
                      ('lgbm neutral − lgbm residual', ('lgbm neutral r50', 'base', 'lgbm residual r50', 'base')),
                      ('lgbm neutral − reversal16', ('lgbm neutral r50', 'base', 'reversal16', 'base')),
                      ('lgbm neutral − reversal16 (close1)', ('lgbm neutral r50', 'close1', 'reversal16', 'close1')),
                      ('ridge neutral − ridge raw neutralised ex ante', ('ridge neutral', 'base', 'ridge raw', 'neut_full')),
                      ('ridge neutral − reversal16', ('ridge neutral', 'base', 'reversal16', 'base'))):
        r = Dd(*args)
        L.append(f'| {lbl} | {fmt(r)} | {folds(r)} |')
    L += ['', '## Market-neutral books (FB simulator, 10 bp per unit turnover)', '',
          '| Arm | Rule | Gross Sharpe | Net Sharpe | Gross ann. | Turnover/day | Break-even cost (bp) |', '|---|---|---|---|---|---|---|']
    sh = lambda x: x.mean() / max(x.std(ddof=1), 1e-12) * np.sqrt(252)
    for (a, rule), c in port.items():
        g, n, t = (np.concatenate(c[k]) for k in ('g', 'n', 't'))
        L.append(f'| {a} | {rule} | {sh(g):+.2f} | {sh(n):+.2f} | {g.mean() * 252:+.3f} | {t.mean():.3f} | {g.mean() / t.mean() * 1e4:+.1f} |')
    (OUT / 'A4b_NEUTRAL_TARGET.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
