"""Closure Task 1: matched 2x2 (features full|style x target residual|neutral), LightGBM 50 rounds, seeds 7/19/42.

  python scripts/closure_matched.py run      # 60 fits -> results/FBAUDIT_20261022/matched/<year>/<cell>_s<seed>.npz
  python scripts/closure_matched.py report   # -> docs/audit_20261022/A11_MATCHED_2x2.md
Exploratory (2019-2023 inspected). Leak-free inputs. Same learner, rounds, seeds, window, preprocessing, dates.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
sys.path.insert(0, 'scripts')
from hypershift.featbench.data import load_fb  # noqa: E402
from hypershift.featbench.prospective import fit_fixed  # noqa: E402
from hypershift.fbaudit import stats as S, diag as D, diag2 as D2, matched as M  # noqa: E402
from hypershift.fbaudit.refit import target_values  # noqa: E402
from fbaudit_refit import corrected_fb  # noqa: E402

RES = Path('results/FBAUDIT_20261022/matched')
OUT = Path('docs/audit_20261022')
SEEDS = (7, 19, 42)
CELLS = [(feat, tgt) for tgt in ('residual', 'neutral') for feat in ('full', 'style')]
DELTA = .005


def cell(feat, tgt):
    return f'{feat}_{tgt}'


def run():
    for f in S.FOLDS:
        todo = [(c, s) for c in CELLS for s in SEEDS if not (RES / str(f) / f'{cell(*c)}_s{s}.npz').exists()]
        if not todo:
            continue
        fb = corrected_fb(load_fb(f, 5), f)
        X = {w: (M.nested_inputs(fb, fb.train, w), M.nested_inputs(fb, fb.evaluate, w)) for w in ('full', 'style')}
        Y = {t: target_values(fb, fb.train, t) for t in ('residual', 'neutral')}
        mtr = fb.eligible[:, fb.train].T
        (RES / str(f)).mkdir(parents=True, exist_ok=True)
        for (feat, tgt), s in todo:
            ytr, m = Y[tgt]
            p = fit_fixed('lgbm', X[feat][0], ytr, m & mtr, X[feat][1], {'n_estimators': 50}, seed=s, threads=8)
            np.savez_compressed(RES / str(f) / f'{cell(feat, tgt)}_s{s}.npz', pred=p.astype(np.float32),
                                dates=fb.dates[fb.evaluate].astype(str))
            print(f, cell(feat, tgt), s, flush=True)


def report():
    ser = {}
    for f in S.FOLDS:
        fb = corrected_fb(load_fb(f, 5), f)
        ev = fb.evaluate
        mask = (fb.y_ok[:, ev] & fb.eligible[:, ev]).T
        neu = fb.neutral[:, ev].T.astype(np.float64)
        tg = {'neutral': neu, 'LIN': D.neutralise_pred(neu, D.exposures(fb, ev, 'full'), mask), 'NL': D2.nl_resid(neu, fb, ev, mask)}
        rr = D2.residual_reversal(fb, ev, 21)
        ser.setdefault(('RR', 'neutral', 0), {})[f] = S.spearman_daily(rr, neu, mask)
        P = {(c, s): np.load(RES / str(f) / f'{cell(*c)}_s{s}.npz')['pred'].astype(np.float64) for c in CELLS for s in SEEDS}
        for (c, s), p in P.items():
            for k, t in tg.items():
                ser.setdefault((cell(*c), k, s), {})[f] = S.spearman_daily(p, t, mask)
        for tgt in ('residual', 'neutral'):
            for s in SEEDS:
                ser.setdefault((f'encompass_{tgt}', 'neutral', s), {})[f] = M.encompass(
                    P[(('full', tgt), s)], P[(('style', tgt), s)], neu, mask)
                ser.setdefault((f'encompassRR_{tgt}', 'neutral', s), {})[f] = M.encompass(P[(('full', tgt), s)], rr, neu, mask)
        print('scored', f, flush=True)
    avg = lambda name, k: {f: np.mean([ser[(name, k, s)][f] for s in SEEDS], 0) for f in S.FOLDS}
    pool = lambda d: S.pooled(d, 'stationary', 10)
    fmt = lambda r: f"{r['pooled']:+.4f} [{r['ci95'][0]:+.4f}, {r['ci95'][1]:+.4f}]"
    yrs = lambda r: ' / '.join(f'{v:+.4f}' for v in r['per_fold'].values())
    seedp = lambda fn: ', '.join(f'{fn(s):+.4f}' for s in SEEDS)
    L = ['# A11 — Matched 2×2: feature information × training target (closure review)', '',
         'Exploratory: the 2019–2023 development years had already been inspected. All inputs are leak-free.', '',
         '**Design.** One learner throughout: LightGBM (FB `LGBM_PARAMS`), 50 fixed rounds, no validation step. Every '
         'cell shares seeds {7, 19, 42}, the FB training window, the evaluation dates and the preprocessing (per-date cs_z '
         'plus sector one-hot).', '',
         '**Cells (features × target):**',
         '- `full` = all 20 FB features + sector one-hot.',
         '- `style` = beta, log_dvol_20, ret_60, vol_60 + sector one-hot. These columns are a subset of `full`.',
         '- `residual` = the FB residual target. `neutral` = the FB evaluation target.', '',
         '**Statistics.** Primary metric: FB neutral RankIC. Series are seed-averaged daily, pooled as the mean of the 5 '
         'year means, with a stationary-bootstrap 95% CI (block 10).', '',
         'Generated by `scripts/closure_matched.py`.', '',
         '## Original comparison (verified from code)', '',
         'In `bcreview_style.py` / A7 the comparison was not matched:',
         '- **the placebo:** `fit_fixed` with 50 rounds, seed 7, **neutral** target, inputs = the four styles + sector one-hot;',
         '- **the "full" model:** the corrected FB early-stopped residual LightGBM, i.e. **residual** target, rounds chosen '
         'on validation per year, 20 features, **no** sector one-hot.',
         '',
         'Target, rounds and feature nesting all differed. The A7 "model − placebo" contrast is therefore confounded and is '
         'superseded by this file.', '',
         '## Absolute cells', '', '| Cell | Neutral RankIC (seed-avg) | Per year | Per seed | LIN | NL |', '|---|---|---|---|---|---|']
    for c in CELLS:
        n = cell(*c)
        r = pool(avg(n, 'neutral'))
        L.append(f"| {n} | {fmt(r)} | {yrs(r)} | {seedp(lambda s: pool(ser[(n, 'neutral', s)])['pooled'])} | "
                 f"{fmt(pool(avg(n, 'LIN')))} | {fmt(pool(avg(n, 'NL')))} |")
    r = pool(ser[('RR', 'neutral', 0)])
    L.append(f'| RR (zero-parameter) | {fmt(r)} | {yrs(r)} | — | — | — |')
    L += ['', '## Question B: incremental information of the extra features (M2, primary)', '',
          '| Contrast | Pooled [95% CI] | 90% CI | Per year | Years > 0 | Per seed | Verdict |', '|---|---|---|---|---|---|---|']
    inc = {}
    for tgt in ('residual', 'neutral'):
        d = {f: avg(cell('full', tgt), 'neutral')[f] - avg(cell('style', tgt), 'neutral')[f] for f in S.FOLDS}
        inc[tgt] = d
        r = pool(d)
        fm = list(r['per_fold'].values())
        sign_ok = max(sum(v > 0 for v in fm), sum(v < 0 for v in fm)) >= 4
        if (r['ci95'][0] > 0 or r['ci95'][1] < 0) and sign_ok:
            v = 'increment DETECTED' + (' (negative)' if r['pooled'] < 0 else '')
        elif -DELTA < r['ci90'][0] and r['ci90'][1] < DELTA:
            v = f'bounded within ±{DELTA}'
        else:
            v = 'UNRESOLVED'
        ps = seedp(lambda s: pool({f: ser[(cell('full', tgt), 'neutral', s)][f] - ser[(cell('style', tgt), 'neutral', s)][f] for f in S.FOLDS})['pooled'])
        L.append(f"| full − style, {tgt} target | {fmt(r)} | [{r['ci90'][0]:+.4f}, {r['ci90'][1]:+.4f}] | {yrs(r)} | "
                 f"{sum(x > 0 for x in fm)}/5 | {ps} | {v} |")
    r = pool({f: inc['residual'][f] - inc['neutral'][f] for f in S.FOLDS})
    L.append(f"| interaction: (full − style)_residual − (full − style)_neutral | {fmt(r)} | [{r['ci90'][0]:+.4f}, {r['ci90'][1]:+.4f}] | {yrs(r)} | "
             f"{sum(x > 0 for x in r['per_fold'].values())}/5 | — | {'DETECTED' if r['ci95'][0] > 0 or r['ci95'][1] < 0 else 'not detected'} |")
    rt = pool({f: avg(cell('full', 'neutral'), 'neutral')[f] - avg(cell('full', 'residual'), 'neutral')[f] for f in S.FOLDS})
    rs = pool({f: avg(cell('style', 'neutral'), 'neutral')[f] - avg(cell('style', 'residual'), 'neutral')[f] for f in S.FOLDS})
    L += ['', '## Target effect within feature set (descriptive)', '', '| Contrast | Pooled [95% CI] | Per year |', '|---|---|---|',
          f'| full: neutral − residual target | {fmt(rt)} | {yrs(rt)} |', f'| style: neutral − residual target | {fmt(rs)} | {yrs(rs)} |']
    L += ['', '## Encompassing (M3): information in `full` beyond `style` (or RR), same target', '',
          '| Test | Pooled [95% CI] | Per year | Per seed |', '|---|---|---|---|']
    for name, lab in (('encompass_residual', 'full | style, residual target'), ('encompass_neutral', 'full | style, neutral target'),
                      ('encompassRR_residual', 'full | RR, residual target'), ('encompassRR_neutral', 'full | RR, neutral target')):
        r = pool(avg(name, 'neutral'))
        L.append(f"| {lab} | {fmt(r)} | {yrs(r)} | {seedp(lambda s: pool(ser[(name, 'neutral', s)])['pooled'])} |")
    L += ['', '## Cells versus RR (neutral metric)', '', '| Contrast | Pooled [95% CI] | Per year |', '|---|---|---|']
    for c in CELLS:
        r = pool({f: avg(cell(*c), 'neutral')[f] - ser[('RR', 'neutral', 0)][f] for f in S.FOLDS})
        L.append(f'| {cell(*c)} − RR | {fmt(r)} | {yrs(r)} |')
    (OUT / 'A11_MATCHED_2x2.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    {'run': run, 'report': report}[sys.argv[1]]()
