"""FB audit: A2 sections 2-3 rerun with leak-free inputs (corrected log_dvol_20/amihud_20 in features and exposures).

  python scripts/fbaudit_mechanism_corrected.py   -> docs/audit_20261022/A2c_MECHANISM_CORRECTED.md
Predictions: corrected early-stopped refits (results/FBAUDIT_20261022/corrected). Exposures: corrected `full` set.
Also writes the style-residual daily series LRV used for next-study power.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
sys.path.insert(0, 'scripts')
from hypershift.featbench.data import load_fb  # noqa: E402
from hypershift.fbaudit import stats as S, diag as D  # noqa: E402
from fbaudit_refit import corrected_fb  # noqa: E402

RES = Path('results/FBAUDIT_20261022/corrected')
FB_ROOT = Path('results/FEATBENCH_SP500_20261022')
OUT = Path('docs/audit_20261022')
ARMS = {'raw (corrected)': ('c', 'lgbm_rich_raw_es'), 'residual (corrected)': ('c', 'lgbm_rich_residual_es'),
        'price residual (leak-free inputs)': ('c', 'lgbm_price_residual_es'), 'reversal16': ('fb', 'block:reversal16'),
        'l1': ('fb', 'block:l1')}


def main():
    ser, r2 = {}, {}
    for f in S.FOLDS:
        fb = corrected_fb(load_fb(f, 5), f)
        ev = fb.evaluate
        ex = {k: D.exposures(fb, ev, k) for k in ('sb', 'full')}
        mask = (fb.y_ok[:, ev] & fb.eligible[:, ev]).T
        neutral = fb.neutral[:, ev].T.astype(np.float64)
        npart = D.neutralise_pred(neutral, ex['full'], mask)
        for a, (src, name) in ARMS.items():
            p = (np.load(RES / str(f) / f'{name}.npz')['pred'] if src == 'c'
                 else S.load_pred(FB_ROOT, f, name)['prediction']).astype(np.float64)
            put = lambda v, s: ser.setdefault((a, v), {}).__setitem__(f, s)
            put('base', S.spearman_daily(p, neutral, mask))
            for k in ('sb', 'full'):
                put(f'neut_{k}', S.spearman_daily(D.neutralise_pred(p, ex[k], mask), neutral, mask))
            put('resid_part', S.spearman_daily(p, npart, mask))
            put('style_part', S.spearman_daily(p, neutral - npart, mask))
            r2.setdefault(a, []).append(float(np.nanmean(D.style_r2(p, ex['full'], mask))))
        print('fold', f, flush=True)
    P = lambda a, v: S.pooled(ser[(a, v)], 'stationary', 10)
    Dd = lambda a, va, b, vb: S.pooled({f: ser[(a, va)][f] - ser[(b, vb)][f] for f in S.FOLDS}, 'stationary', 10)
    fmt = lambda r: f"{r['pooled']:+.4f} [{r['ci95'][0]:+.4f}, {r['ci95'][1]:+.4f}]"
    folds = lambda r: ' / '.join(f'{v:+.4f}' for v in r['per_fold'].values())
    L = ['# A2c — Mechanism rerun with leak-free inputs', '',
         'Same as A2 sections 2–3, but every input is leak-free:', '',
         '- `log_dvol_20` and `amihud_20` use unadjusted close × volume (A5) in the model features, the residual-target '
         'regressor and the `full` exposure set.',
         '- Predictions are the corrected early-stopped refits (seed 7).', '',
         'Generated by `scripts/fbaudit_mechanism_corrected.py`.', '',
         '| Arm | Neutral RankIC | Neutralised (sector+beta) | Neutralised (full) | vs style-residual part | vs style-explained part | Style R² (full) |',
         '|---|---|---|---|---|---|---|']
    for a in ARMS:
        L.append(f"| {a} | {fmt(P(a, 'base'))} | {fmt(P(a, 'neut_sb'))} | {fmt(P(a, 'neut_full'))} | "
                 f"{fmt(P(a, 'resid_part'))} | {fmt(P(a, 'style_part'))} | {np.mean(r2[a]):.3f} |")
    L += ['', '| Contrast | Pooled [95% CI] | Fold means |', '|---|---|---|']
    raw, res = 'raw (corrected)', 'residual (corrected)'
    rows = {}
    for lbl, args in (('G = residual − raw', (res, 'base', raw, 'base')),
                      ('G_n(full) = raw neutralised − raw', (raw, 'neut_full', raw, 'base')),
                      ('G_n(sb) = raw neutralised(sb) − raw', (raw, 'neut_sb', raw, 'base')),
                      ('residual − raw neutralised(full)', (res, 'base', raw, 'neut_full')),
                      ('residual neutralised − raw neutralised (both full)', (res, 'neut_full', raw, 'neut_full')),
                      ('residual − reversal16 on style-residual part', (res, 'resid_part', 'reversal16', 'resid_part'))):
        r = Dd(*args)
        rows[lbl] = r
        L.append(f'| {lbl} | {fmt(r)} | {folds(r)} |')
    G, Gn, rr = rows['G = residual − raw']['pooled'], rows['G_n(full) = raw neutralised − raw']['pooled'], rows['residual − raw neutralised(full)']
    if Gn >= .5 * G and rr['ci95'][0] <= 0 <= rr['ci95'][1]:
        v = 'mostly tilt removal'
    elif rr['pooled'] >= .5 * G and rr['ci95'][0] > 0:
        v = 'learning gain'
    else:
        v = 'mixed'
    L += ['', f'**T2 verdict, leak-free: {v}** (G {G:+.4f}, G_n {Gn:+.4f}, residual − neutralised raw {fmt(rr)}).', '']
    # power for the next study: style-residual metric of the residual model
    s = ser[(res, 'resid_part')]
    lrv = float(np.mean([S.pooled({0: x}, 'stationary', 10, 3000)['se'] ** 2 * len(x) for x in s.values()]))
    L += ['## Long-run variance of the style-residual RankIC (residual model, leak-free) for power', '',
          f'LRV per day = {lrv:.4f}. SE over n days = √(LRV/n). MDE (80%, α .05) at 2,000 days = '
          f'{2.8 * np.sqrt(lrv / 2000):.4f}; at 2,500 days = {2.8 * np.sqrt(lrv / 2500):.4f}; at 1,250 days = '
          f'{2.8 * np.sqrt(lrv / 1250):.4f}. Days for MDE 0.008 = {lrv * (2.8 / .008) ** 2:.0f}; for 0.010 = '
          f'{lrv * (2.8 / .010) ** 2:.0f}.']
    (OUT / 'A2c_MECHANISM_CORRECTED.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
