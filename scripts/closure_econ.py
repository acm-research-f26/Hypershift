"""Closure Task 4: paired economics of the buffered weekly neutral book (M5). Existing predictions only.

  python scripts/closure_econ.py   -> appends Part 2 to docs/audit_20261022/A13_LF_AND_ECON.md
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
sys.path.insert(0, 'scripts')
from hypershift.featbench.data import load_fb, OHLCV, PANEL  # noqa: E402
from hypershift.fbaudit import stats as S, diag as D, diag2 as D2, book  # noqa: E402
from fbaudit_refit import corrected_fb  # noqa: E402

COR = Path('results/FBAUDIT_20261022/corrected')
MAT = Path('results/FBAUDIT_20261022/matched')
OUT = Path('docs/audit_20261022')
ARMS = ['residual LightGBM (A8 model)', 'full/residual (matched, s7)', 'style/residual (matched, s7)',
        'style/neutral (matched, s7)', 'RR', 'raw LightGBM neutralised']
PAIRS = [('residual LightGBM (A8 model)', b) for b in ARMS[2:]] + [('full/residual (matched, s7)', 'style/residual (matched, s7)')]


def sharpe(x):
    return float(x.mean() / max(x.std(ddof=1), 1e-12) * np.sqrt(252))


def main():
    o = np.load(OHLCV); z = np.load(PANEL)
    ohlcv_all = o['ohlcv'][z['identity_ok'].astype(bool)].astype(np.float64)
    g, t = {}, {}
    for f in S.FOLDS:
        fb = corrected_fb(load_fb(f, 5), f)
        ev = fb.evaluate
        mask = (fb.y_ok[:, ev] & fb.eligible[:, ev]).T
        raw = np.load(COR / str(f) / 'lgbm_rich_raw_es.npz')['pred'].astype(np.float64)
        ld = lambda n: np.load(MAT / str(f) / f'{n}_s7.npz')['pred'].astype(np.float64)
        preds = {ARMS[0]: np.load(COR / str(f) / 'lgbm_rich_residual_es.npz')['pred'].astype(np.float64),
                 ARMS[1]: ld('full_residual'), ARMS[2]: ld('style_residual'), ARMS[3]: ld('style_neutral'),
                 ARMS[4]: D2.residual_reversal(fb, ev, 21),
                 ARMS[5]: D.neutralise_pred(raw, D.exposures(fb, ev, 'full'), mask)}
        T = fb.price.shape[1]
        for a, p in preds.items():
            for ex in ('close1', 'open1'):
                out = book.simulate_book(p, fb, ev, 'weekly_buffer', ex, ohlcv=ohlcv_all[:, :T])
                g.setdefault((a, ex), {})[f] = out['gross']; t.setdefault((a, ex), {})[f] = out['traded']
        print('fold', f, flush=True)
    net = lambda a, ex, c: {f: g[(a, ex)][f] - c * 1e-4 * t[(a, ex)][f] for f in S.FOLDS}
    L = ['', '## Part 2: paired economics of the buffered weekly neutral book (M5)', '',
         'Book as in A8 (`weekly_buffer`: sector-neutral 10% long/short, 10%/30% buffer, equal-weight beta hedge, drift, '
         'hedge trades costed). Arms use existing predictions; the matched cells come from A11, seed 7. Generated by '
         '`scripts/closure_econ.py`.', '',
         '### Net Sharpe per year at 5 bp', '', '| Arm | Exec | ' + ' | '.join(str(f) for f in S.FOLDS) + ' | Pooled |', '|---|---|' + '---|' * 6]
    for a in ARMS:
        for ex in ('close1', 'open1'):
            n = net(a, ex, 5)
            L.append(f'| {a} | {ex} | ' + ' | '.join(f'{sharpe(n[f]):+.2f}' for f in S.FOLDS) +
                     f' | {sharpe(np.concatenate(list(n.values()))):+.2f} |')
    L += ['', '### Paired daily net-return differences (annualised mean, 95% CI, stationary bootstrap block 10)', '',
          '| Contrast | Exec | 5 bp | 10 bp | Years > 0 (5 bp) |', '|---|---|---|---|---|']
    for a, b in PAIRS:
        for ex in ('close1', 'open1'):
            cells = []
            for c in (5, 10):
                na, nb = net(a, ex, c), net(b, ex, c)
                r = S.pooled({f: na[f] - nb[f] for f in S.FOLDS}, 'stationary', 10)
                cells.append(f"{r['pooled'] * 252:+.3f} [{r['ci95'][0] * 252:+.3f}, {r['ci95'][1] * 252:+.3f}]")
                if c == 5:
                    pos = sum(v > 0 for v in r['per_fold'].values())
            L.append(f'| {a} − {b} | {ex} | {cells[0]} | {cells[1]} | {pos}/5 |')
    L += ['', '**Advantage rule (M5):** the CI excludes 0. Selection caveat: the A8 model and the buffered rule were chosen '
          'on these same years from 5 arms × 3 schedules × 2 executions. The cost model is linear, with no borrow, '
          'financing or impact.']
    with open(OUT / 'A13_LF_AND_ECON.md', 'a', encoding='utf-8') as fh:
        fh.write('\n'.join(L) + '\n')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
