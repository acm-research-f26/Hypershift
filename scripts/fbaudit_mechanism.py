"""FB audit Task 2: why does the residual target help, and does any neutral IC survive delayed execution?

  python scripts/fbaudit_mechanism.py   -> docs/audit_20261022/A2_MECHANISM.md (+ results/FBAUDIT_20261022/mechanism.npz)
Zero refits: saved seed-7 predictions; exposures recomputed ex ante from the FB feature cache (load_fb).
"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
from hypershift.featbench.data import load_fb, OHLCV, PANEL  # noqa: E402
from hypershift.fbaudit import stats as S, diag as D  # noqa: E402

ROOT = Path('results/FEATBENCH_SP500_20261022')
OUT = Path('docs/audit_20261022')
RES = Path('results/FBAUDIT_20261022')
ARMS = ['lgbm:rich', 'lgbm:rich:sector', 'lgbm:rich:residual', 'lgbm:price', 'ridge:rich', 'ridge:rich:sector',
        'ridge:rich:residual', 'ridge:lags', 'mlp:rich', 'block:reversal16', 'block:l1', 'block:l2_5']


def resid_part(y, expo, mask):
    return D.neutralise_pred(y, expo, mask)


def main():
    OUT.mkdir(parents=True, exist_ok=True); RES.mkdir(parents=True, exist_ok=True)
    o = np.load(OHLCV); z = np.load(PANEL)
    ohlcv_all = o['ohlcv'][z['identity_ok'].astype(bool)].astype(np.float64)
    ser = {}   # (arm, variant) -> {fold: daily series}
    r2 = {}    # (arm, kind) -> list of fold mean R^2
    fallback = {}
    for f in S.FOLDS:
        fb = load_fb(f, 5)
        ev = fb.evaluate
        ex = {k: D.exposures(fb, ev, k) for k in ('sb', 'full')}
        lab = {m: D.shifted_neutral(fb, ev, m, ohlcv_all[:, :fb.price.shape[1]]) for m in ('close1', 'open1')}
        keep = lab['close1'][3] & lab['open1'][3]
        z0 = S.load_pred(ROOT, f, 'lgbm:rich')
        assert np.array_equal(z0['signals'], ev), f
        mask, neutral = z0['mask'], z0['neutral'].astype(np.float64)
        npart = resid_part(neutral, ex['full'], mask)          # style-residual part of the neutral target
        epart = neutral - npart                                  # style-explained part
        fallback[f] = int((mask.sum(1) < 30).sum())
        for arm in ARMS:
            p = S.load_pred(ROOT, f, arm)['prediction'].astype(np.float64)
            put = lambda v, s: ser.setdefault((arm, v), {}).__setitem__(f, s)
            put('base', S.spearman_daily(p, neutral, mask))
            for k in ('sb', 'full'):
                put(f'neut_{k}', S.spearman_daily(D.neutralise_pred(p, ex[k], mask), neutral, mask))
                r2.setdefault((arm, k), []).append(float(np.nanmean(D.style_r2(p, ex[k], mask))))
            put('on_resid_part', S.spearman_daily(p, npart, mask))
            put('on_style_part', S.spearman_daily(p, epart, mask))
            put('same_kept', S.spearman_daily(p[keep], neutral[keep], mask[keep]))
            for m in ('close1', 'open1'):
                neu, _, ok, _ = lab[m]
                put(m, S.spearman_daily(p[keep], neu[keep], ok[keep]))
        print('fold', f, 'done', flush=True)
    np.savez_compressed(RES / 'mechanism.npz', **{f'{a}|{v}|{f}': s for (a, v), d in ser.items() for f, s in d.items()})

    P = lambda a, v: S.pooled(ser[(a, v)], 'stationary', 10)
    D_ = lambda a, va, b, vb: S.pooled({f: ser[(a, va)][f] - ser[(b, vb)][f] for f in S.FOLDS}, 'stationary', 10)
    fmt = lambda r: f"{r['pooled']:+.4f} [{r['ci95'][0]:+.4f}, {r['ci95'][1]:+.4f}]"
    folds = lambda r: ' / '.join(f'{v:+.4f}' for v in r['per_fold'].values())
    L = ['# A2 — Mechanism of the residual-target gain and execution-lag robustness', '',
         'Exploratory audit, zero refits. Saved seed-7 predictions (2019–2023 folds); exposures measured at the signal '
         'close (sector dummies + z-scored beta [`sb`], plus log_dvol_20, ret_60, vol_60 [`full`] — the residual-target '
         'regressors). Pooled = mean of fold means; 95% CI stationary bootstrap block 10. Generated by '
         '`scripts/fbaudit_mechanism.py`.', '']
    L += ['## 1. Style content of predictions', '', 'Mean per-date R² of prediction ranks on the exposures.', '',
          '| Arm | R² on sector+beta | R² on full residual set |', '|---|---|---|']
    for a in ARMS:
        L.append(f"| {a} | {np.mean(r2[(a, 'sb')]):.3f} | {np.mean(r2[(a, 'full')]):.3f} |")
    # T2
    L += ['', '## 2. Ex-ante neutralisation of predictions (predeclared T2)', '',
          'Each arm\'s predictions are residualised per date on the exposures (no labels used), then re-scored on the '
          'same factor-neutral target.', '',
          '| Arm | As saved | Neutralised on sector+beta | Neutralised on full set |', '|---|---|---|---|']
    for a in ARMS:
        L.append(f"| {a} | {fmt(P(a, 'base'))} | {fmt(P(a, 'neut_sb'))} | {fmt(P(a, 'neut_full'))} |")
    L += ['', '| Contrast | Pooled [95% CI] | Fold means |', '|---|---|---|']
    rows = {}
    for m in ('lgbm', 'ridge'):
        raw, res = f'{m}:rich', f'{m}:rich:residual'
        for lbl, args in ((f'G = {res} − {raw}', (res, 'base', raw, 'base')),
                          (f'G_n(full) = {raw} neutralised − {raw}', (raw, 'neut_full', raw, 'base')),
                          (f'G_n(sb) = {raw} neutralised(sb) − {raw}', (raw, 'neut_sb', raw, 'base')),
                          (f'{res} − {raw} neutralised(full)', (res, 'base', raw, 'neut_full')),
                          (f'{res} neutralised − {raw} neutralised (both full)', (res, 'neut_full', raw, 'neut_full'))):
            r = D_(*args); rows[lbl] = r
            L.append(f'| {lbl} | {fmt(r)} | {folds(r)} |')
    verdicts = {}
    for m in ('lgbm', 'ridge'):
        raw, res = f'{m}:rich', f'{m}:rich:residual'
        G = rows[f'G = {res} − {raw}']['pooled']
        Gn = rows[f'G_n(full) = {raw} neutralised − {raw}']['pooled']
        rr = rows[f'{res} − {raw} neutralised(full)']
        if Gn >= .5 * G and rr['ci95'][0] <= 0 <= rr['ci95'][1]:
            v = 'mostly tilt removal'
        elif rr['pooled'] >= .5 * G and rr['ci95'][0] > 0:
            v = 'learning gain'
        else:
            v = 'mixed'
        verdicts[m] = v
        L.append(f'\n**T2 verdict ({m}): {v}** (G {G:+.4f}, G_n {Gn:+.4f}, residual − neutralised raw {fmt(rr)}).')
    # decomposition
    L += ['', '## 3. Decomposition of the neutral target', '',
          'neutral = style-explained part (per-date OLS fit on the full exposure set) + style-residual part. Each arm\'s '
          'predictions scored against each part.', '',
          '| Arm | Neutral (as saved) | vs style-residual part | vs style-explained part |', '|---|---|---|---|']
    for a in ARMS:
        L.append(f"| {a} | {fmt(P(a, 'base'))} | {fmt(P(a, 'on_resid_part'))} | {fmt(P(a, 'on_style_part'))} |")
    # T3 lag
    L += ['', '## 4. Execution lag (predeclared T3)', '',
          'Same-close = FB label (close t → close t+5), restricted to signals that also have both delayed labels. '
          'close1 = close t+1 → close t+6; open1 = open t+1 → close t+5. Retained = delayed / same-close pooled.', '',
          '| Arm | Same-close | close1 | open1 | Retained close1 | Retained open1 | T3 verdict (close1) |',
          '|---|---|---|---|---|---|---|']
    lag = {}
    for a in ARMS:
        s, c, op = P(a, 'same_kept'), P(a, 'close1'), P(a, 'open1')
        rc = c['pooled'] / s['pooled'] if s['pooled'] > 0 else float('nan')
        ro = op['pooled'] / s['pooled'] if s['pooled'] > 0 else float('nan')
        if s['pooled'] <= 0:
            v = 'n/a (same-close ≤ 0)'
        elif rc >= .5 and c['ci95'][0] > 0:
            v = 'robust'
        elif rc < .25:
            v = 'bounce-dominated'
        else:
            v = 'partial'
        lag[a] = v
        L.append(f'| {a} | {fmt(s)} | {fmt(c)} | {fmt(op)} | {rc:.0%} | {ro:.0%} | {v} |')
    L += ['', '| Delayed contrast | Pooled [95% CI] | Fold means |', '|---|---|---|']
    for a, b in (('lgbm:rich:residual', 'lgbm:rich'), ('lgbm:rich:residual', 'block:reversal16'), ('ridge:lags', 'block:reversal16')):
        for m in ('close1', 'open1'):
            r = D_(a, m, b, m)
            L.append(f'| {a} − {b} ({m}) | {fmt(r)} | {folds(r)} |')
    # spread10
    L += ['', '## 5. Mean daily top-minus-bottom decile neutral 5-day return (`neutral_spread10`, metrics.json)', '',
          '| Arm | Fold values | Mean (5-day, gross) |', '|---|---|---|']
    for a in ARMS:
        v = [json.load(open(ROOT / str(f) / a.replace(':', '__') / 'seed_7' / 'metrics.json'))['neutral_spread10'] for f in S.FOLDS]
        L.append(f"| {a} | {' / '.join(f'{x:+.4f}' for x in v)} | {np.mean(v):+.4f} |")
    L += ['', f'Evaluation dates with < 30 masked stocks per fold (residual fallback would fire on such dates): {fallback}.']
    (OUT / 'A2_MECHANISM.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    json.dump({'T2': verdicts, 'T3': lag}, open(RES / 'mechanism_verdicts.json', 'w'), indent=1)
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
