"""Closure Task 2: can the evaluation tell "style-only nonlinear" from "planted incremental information"? (M4)

  python scripts/closure_synth.py   -> docs/audit_20261022/A12_SYNTHETIC.md
"""
import sys
from pathlib import Path

import numpy as np
from scipy.stats import rankdata

sys.path.insert(0, 'src')
from hypershift.featbench.prospective import fit_fixed  # noqa: E402
from hypershift.fbaudit import stats as S, diag as D, matched as M  # noqa: E402

OUT = Path('docs/audit_20261022')
TRAIN, EVAL = 750, 500
REPS = (0, 1, 2)


def cs_z(x):
    mu, sd = x.mean(0, keepdims=True), x.std(0, keepdims=True)
    return np.clip((x - mu) / np.maximum(sd, 1e-12), -5, 5)


def inputs(p, cols):
    X = cs_z(p['X'][..., cols]).transpose(1, 0, 2)                     # [T, N, F]
    sec = (p['sectors'][:, None] == np.unique(p['sectors'])[None]).astype(float)
    return np.concatenate([X, np.broadcast_to(sec, (X.shape[0],) + sec.shape)], -1)


def style_expo(p, quintiles):
    X = p['X'][..., :4].transpose(1, 0, 2)                              # [T, N, 4]
    sec = (p['sectors'][:, None] == np.unique(p['sectors'])[None]).astype(float)
    cols = [np.broadcast_to(sec, (X.shape[0],) + sec.shape), cs_z(p['X'][..., :4]).transpose(1, 0, 2)]
    if quintiles:
        q = np.zeros(X.shape[:2] + (16,))
        for t in range(X.shape[0]):
            for j in range(4):
                b = np.minimum((rankdata(X[t, :, j]) - 1) / X.shape[1] * 5, 4.999).astype(int)
                for k in range(1, 5):
                    q[t, :, 4 * j + k - 1] = b == k
        cols.append(q)
    return np.concatenate(cols, -1)


def blocks(s):
    return {i: s[i * 100:(i + 1) * 100] for i in range(len(s) // 100)}


def main():
    rows = {}
    for sc in ('S', 'I'):
        for rep in REPS:
            p = M.synth_panel(sc, rep)
            y = (p['y'] - p['y'].mean(0, keepdims=True)).T                    # [T, N] date-demeaned target
            m = np.ones_like(y, bool)
            tr, ev = slice(0, TRAIN), slice(TRAIN, TRAIN + EVAL)
            P = {}
            for name, cols in (('full', list(range(10))), ('style', [0, 1, 2, 3])):
                Xi = inputs(p, cols)
                P[name] = fit_fixed('lgbm', Xi[tr], y[tr], m[tr], Xi[ev], {'n_estimators': 50}, seed=7, threads=8)
            ye, me = y[ev], m[ev]
            pe = {'X': p['X'][:, ev], 'sectors': p['sectors']}
            t_lin = D.neutralise_pred(ye, style_expo(pe, False), me)
            t_nl = D.neutralise_pred(ye, style_expo(pe, True), me)
            for name in P:
                for k, t in (('raw', ye), ('LIN', t_lin), ('NL', t_nl)):
                    rows.setdefault((sc, name, k), []).append(S.pooled(blocks(S.spearman_daily(P[name], t, me)), 'stationary', 10))
            inc = S.spearman_daily(P['full'], ye, me) - S.spearman_daily(P['style'], ye, me)
            rows.setdefault((sc, 'increment', 'raw'), []).append(S.pooled(blocks(inc), 'stationary', 10))
            rows.setdefault((sc, 'encompass', 'raw'), []).append(S.pooled(blocks(M.encompass(P['full'], P['style'], ye, me)), 'stationary', 10))
            print(sc, rep, flush=True)
    fmt = lambda r: f"{r['pooled']:+.4f} [{r['ci95'][0]:+.4f}, {r['ci95'][1]:+.4f}]"
    L = ['# A12 — Synthetic validation: can the evaluation separate style-only from incremental information? (M4)', '',
         '**Synthetic panel.** 400 stocks, 10 sectors, 750 training and 500 evaluation dates.',
         '- 4 persistent style characteristics (AR(1) 0.98) and 6 other features (AR(1) 0.5).',
         '- **Returns (scenario S):** a nonlinear function of the styles with interactions, '
         'tanh(s1·s2) + (s3²−1)·sign(s4) + sector-specific slope · s4, standardised, plus noise (SD 10).',
         '- **Scenario I:** S plus a planted incremental term 0.15 × x1, where x1 is a non-style feature.', '',
         '**Learner.** Matched LightGBM, 50 rounds, seed 7, trained on the date-demeaned return. `full` = all 10 features '
         '+ sector one-hot; `style` = the 4 styles + sector one-hot.', '',
         '**Metrics:**',
         '- **raw** = RankIC vs the date-demeaned return;',
         '- **LIN / NL** = RankIC vs the return residualised per date on sector + linear styles / + style quintile dummies;',
         '- **increment** = full − style on raw;',
         '- **encompass** = full residualised on style (M3).', '',
         'Each cell gives the pooled value with a stationary-bootstrap 95% CI over 5 blocks of 100 evaluation dates, for '
         f'replicates {REPS}. Generated by `scripts/closure_synth.py`.', '',
         '| Scenario | Series | Metric | ' + ' | '.join(f'rep {r}' for r in REPS) + ' |', '|---|---|---|' + '---|' * len(REPS)]
    for (sc, name, k), rs in rows.items():
        L.append(f'| {sc} | {name} | {k} | ' + ' | '.join(fmt(r) for r in rs) + ' |')
    ex0 = lambda r: r['ci95'][0] > 0 or r['ci95'][1] < 0
    s_style_pos = all(r['ci95'][0] > 0 for k in ('LIN', 'NL') for r in rows[('S', 'style', k)])
    s_no_inc = all(not ex0(r) for r in rows[('S', 'increment', 'raw')])
    i_inc = all(r['ci95'][0] > 0 for r in rows[('I', 'increment', 'raw')])
    s_no_enc = all(not ex0(r) for r in rows[('S', 'encompass', 'raw')])
    i_enc = all(r['ci95'][0] > 0 for r in rows[('I', 'encompass', 'raw')])
    L += ['', '## M4 verdict', '',
          f"- Residualised metrics reward the style-only model when returns are style-only (S: style LIN and NL CI > 0 in all reps): **{'yes' if s_style_pos else 'no'}**.",
          f"- Matched increment gives no false increment in S (CI includes 0 in all reps): **{'yes' if s_no_inc else 'no'}**; detects the planted increment in I (CI > 0 in all reps): **{'yes' if i_inc else 'no'}**.",
          f"- Encompassing: no false positive in S: **{'yes' if s_no_enc else 'no'}**; detects I: **{'yes' if i_enc else 'no'}**.",
          f"- **PASS** (matched increment discriminates and residualised metrics are shown to fail): **{'PASS' if s_style_pos and s_no_inc and i_inc else 'FAIL'}**."]
    (OUT / 'A12_SYNTHETIC.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
