"""WP-A robustness of the style-only book (saved predictions only; no retraining).

Checks: cost sensitivity and worst calendar year (predeclared rules), seeds 7/19/42 and their average, point-in-time
S&P 500 membership eligibility, and long-leg vs short-leg contributions (survivorship pattern check).
  python scripts/strategy_style_robust.py   -> docs/strategy_20261022/STYLE_ROBUST.md
"""
import copy
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
from hypershift.strategy import study as ST, engine as EN, factors as FA  # noqa: E402

MAT = Path('results/FBAUDIT_20261022/matched')
OUT = Path('docs/strategy_20261022/STYLE_ROBUST.md')
END = np.datetime64('2023-12-31')


def scores(d, cell, seeds):
    idx = {str(x): i for i, x in enumerate(d.dates.astype(str))}
    sc = {}
    for f in (2019, 2020, 2021, 2022, 2023):
        P = [np.load(MAT / str(f) / f'{cell}_s{s}.npz') for s in seeds]
        dates = P[0]['dates']
        pred = np.mean([np.argsort(np.argsort(p['pred'], 1), 1) for p in P], 0) if len(P) > 1 else P[0]['pred']
        for k, day in enumerate(dates):
            if k % 5 == 0 and str(day) in idx and idx[str(day)] + 1 < len(d.dates):
                sc[idx[str(day)] + 1] = pred[k].astype(np.float64)
    return sc


def books(d, sc, end):
    ls = EN.run(sc, d, mode='LS', top=.1, band=.3, execution='open', cost_bp=0, borrow_bp=50, end=end)
    lo = EN.run(sc, d, mode='LO', top=.2, band=.4, execution='open', cost_bp=0, borrow_bp=0, end=end)
    be = EN.benchmark_ew(sc, d, execution='open', cost_bp=0, end=end)
    return ls, lo, be


def row(name, series_by_cost, traded_yr, dates, ff):
    s = {c: ST.ir_stats(series_by_cost[c]) for c in (5, 10, 20, 30)}
    worst = min(ST.per_year(series_by_cost[10], dates).values())
    a = FA.attribute(series_by_cost[10], dates, ff)
    return (f"| {name} | {s[5]['ir']:+.2f} | {s[10]['ir']:+.2f} [{s[10]['ci'][0]:+.2f}, {s[10]['ci'][1]:+.2f}] | {s[20]['ir']:+.2f} | "
            f"{s[30]['ir']:+.2f} | {s[10]['ann_mean']:+.3f} | {worst:+.3f} | {traded_yr:.2f} | {a['alpha_ann']:+.3f} ({a['t']:+.2f}) | {a['r2']:.2f} |")


def main():
    d = ST.load_data()
    ff = FA.load_ff('data/factors')
    end = int(np.searchsorted(d.dates, END, side='right') - 1)
    dp = copy.copy(d)
    dp.eligible = ST.pit_eligible(d)
    L = ['# Style-only book: robustness on saved predictions (2019–2023, exploratory, survivor-trained models)', '',
         'Books as in `STYLE_BOOK.md`, with weekly rebalancing and next-open execution:',
         '- **LS:** sector-neutral 10%/30% band, beta-hedged, borrow 50 bp/yr;',
         '- **LO:** 20%/40% band, against an equal-weight benchmark on the same days.', '',
         'IR columns are net Sharpe (LS) or active IR (LO) at each cost. The worst year uses 10 bp. Alpha: FF5 + MOM + '
         'ST_Rev, Newey–West 10 lags, 10 bp. Generated by `scripts/strategy_style_robust.py`.', '',
         '| Variant | IR @5 | @10 [95% CI] | @20 | @30 | Ann. @10 | Worst year @10 | Traded/yr | FF alpha (t) | R² |',
         '|---|---|---|---|---|---|---|---|---|---|']
    for label, data, seeds in (('seed 7', d, (7,)), ('seed 19', d, (19,)), ('seed 42', d, (42,)), ('3-seed rank average', d, (7, 19, 42)),
                               ('seed 7, PIT membership', dp, (7,)), ('3-seed avg, PIT membership', dp, (7, 19, 42))):
        sc = scores(data, 'style_residual', seeds)
        ls, lo, be = books(data, sc, end)
        yrs = len(ls['gross']) / 252
        L.append(row(f'style_residual LS, {label}', {c: ST.net(ls, c) for c in (5, 10, 20, 30)}, ls['traded'].sum() / yrs, ls['dates'], ff))
        L.append(row(f'style_residual LO active, {label}', {c: ST.net(lo, c) - ST.net(be, c) for c in (5, 10, 20, 30)},
                     lo['traded'].sum() / yrs, lo['dates'], ff))
        print(label, flush=True)
    # leg decomposition (seed 7, close execution for exact contributions)
    sc = scores(d, 'style_residual', (7,))
    tr = EN.run(sc, d, mode='LS', top=.1, band=.3, execution='close', cost_bp=0, borrow_bp=0, end=end, trace=True)
    W, R = tr['w_start'], tr['r']
    big = np.abs(W) > .002
    legs = {'long leg': (W * R * (big & (W > 0))).sum(1), 'short leg': (W * R * (big & (W < 0))).sum(1),
            'hedge': (W * R * ~big).sum(1)}
    L += ['', '## Leg decomposition (LS, seed 7, next-close execution, gross)', '',
          '| Component | Ann. contribution | Sharpe of contribution |', '|---|---|---|']
    for k, v in legs.items():
        L.append(f'| {k} | {v.mean() * 252:+.3f} | {v.mean() / max(v.std(ddof=1), 1e-12) * np.sqrt(252):+.2f} |')
    # exposure profile: share of long/short weight in "beaten-down & volatile" names (ret_60 bottom tercile, vol_60 top)
    t_idx = np.searchsorted(d.dates, tr['dates'])
    prof = {'long': [], 'short': []}
    for k in range(0, len(t_idx), 5):
        t = t_idx[k] - 1
        e = d.eligible[:, t]
        r60 = d.price[:, t] / np.maximum(d.price[:, t - 60], 1e-12) - 1
        rr = np.diff(np.log(np.maximum(d.price[:, t - 60:t + 1], 1e-12)), axis=1)
        v60 = rr.std(1)
        lo3 = r60 <= np.nanquantile(r60[e], 1 / 3)
        hi3 = v60 >= np.nanquantile(v60[e], 2 / 3)
        bd = lo3 & hi3 & e
        w = W[k]
        for side, m in (('long', big[k] & (w > 0)), ('short', big[k] & (w < 0))):
            if m.any():
                prof[side].append(np.abs(w[m & bd]).sum() / np.abs(w[m]).sum())
    L += ['', f"Share of leg weight in beaten-down & volatile names (60-day return bottom tercile AND 60-day vol top tercile; "
          f"about 1/9 to 1/3 of the universe, depending on the correlation): long leg {np.mean(prof['long']):.2f}, "
          f"short leg {np.mean(prof['short']):.2f}.", '',
          '**Survivorship pattern to watch for:** a long leg concentrated in beaten-down volatile names that earns most of '
          'the return. Firms of that kind that later failed are absent from a current-constituent universe.']
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
