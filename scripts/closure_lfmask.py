"""Closure Task 3: size of the v1-LF eligibility-mask discrepancy on development data.

  python scripts/closure_lfmask.py   -> docs/audit_20261022/A13_LF_AND_ECON.md (part 1)
Emulates v1-LF's leak-strict dropping with the audit's unadjusted download (data/audit/yf_unadjusted), then scores
the leak-free residual LightGBM on (a) the neutral target computed with the pre-LF mask and (b) the target
recomputed with the post-LF mask (the fix). Exploratory, dev 2019-2023 only.
"""
import copy
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
from hypershift.featbench.data import load_fb, OHLCV, PANEL  # noqa: E402
from hypershift.fbaudit import stats as S  # noqa: E402
from hypershift.fbaudit.prospective_lf import make_leakfree  # noqa: E402

COR = Path('results/FBAUDIT_20261022/corrected')
OUT = Path('docs/audit_20261022')


def main():
    z = np.load(PANEL); o = np.load(OHLCV)
    ident = z['identity_ok'].astype(bool)
    ohlcv = o['ohlcv'][ident].astype(np.float64)
    raw = np.load('data/audit/yf_unadjusted/unadjusted.npz')
    old, new, drops, maxd = {}, {}, {}, {}
    for f in S.FOLDS:
        fb = load_fb(f, 5)
        T = fb.X.shape[1]
        rc = np.full((fb.X.shape[0], T), np.nan)
        n = min(T, raw['close'].shape[1])
        rc[:, :n] = raw['close'][:, :n]
        before = fb.neutral.copy()
        lf = make_leakfree(copy.copy(fb), ohlcv, rc)
        ev = fb.evaluate
        m = (lf.y_ok[:, ev] & lf.eligible[:, ev]).T
        p = np.load(COR / str(f) / 'lgbm_rich_residual_es.npz')['pred'].astype(np.float64)
        a = S.spearman_daily(p, before[:, ev].T, m)
        b = S.spearman_daily(p, lf.neutral[:, ev].T, m)
        old[f], new[f] = a, b
        drops[f] = int((fb.eligible[:, ev] & ~lf.eligible[:, ev]).sum())
        maxd[f] = float(np.abs(a - b).max())
        print(f, drops[f], maxd[f], flush=True)
    d = S.pooled({f: new[f] - old[f] for f in S.FOLDS}, 'stationary', 10)
    L = ['# A13 — v1-LF mask discrepancy and paired economics (closure review)', '',
         '## Part 1: v1-LF eligibility-mask discrepancy (dev emulation)', '',
         'v1-LF marks a stock-day ineligible when its 20-day window lacks an unadjusted close. Before this fix, '
         '`make_leakfree` left `fb.neutral` as `load_range` computed it with the **pre-LF** mask. Dropped stocks therefore '
         'still entered the equal-weight market mean and the sector demeaning of the evaluation target. The fix recomputes '
         '`neutral` with the post-LF mask, exactly as `load_range` does (regression test '
         '`test_lf_neutral_uses_post_lf_mask`).', '',
         'Emulation on dev: the audit\'s unadjusted download is used as the "raw" input. Scoring uses the leak-free '
         'residual LightGBM on the post-LF mask with both target versions. Generated by `scripts/closure_lfmask.py`.', '',
         '| Year | Eligible stock-days dropped by LF (evaluation dates) | Max abs daily RankIC change |', '|---|---|---|']
    for f in S.FOLDS:
        L.append(f'| {f} | {drops[f]} | {maxd[f]:.2e} |')
    L += ['', f"Pooled change in neutral RankIC (fixed − unfixed): {d['pooled']:+.2e} [{d['ci95'][0]:+.2e}, {d['ci95'][1]:+.2e}].", '']
    (OUT / 'A13_LF_AND_ECON.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
