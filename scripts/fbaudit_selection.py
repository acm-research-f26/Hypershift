POOL = ['ridge:rich', 'lgbm:rich', 'ridge:price', 'lgbm:price', 'ridge:lags',
        'ridge:rich:sector', 'ridge:rich:residual', 'lgbm:rich:sector', 'lgbm:rich:residual'] + \
       [f'{m}:rich:raw:5:{r}' for m in ('ridge', 'lgbm') for r in ('raw', 'cs_rank', 'sector_z', 'volscaled_z')]
WINNER = 'lgbm:rich:residual'
PORT_ARMS = ['block:reversal16', 'block:l1', 'lgbm:rich', 'lgbm:rich:residual']


def joint(arms, key='neutral_RankIC'):
    """{fold: [n_common, A]} on dates common to all arms."""
    out = {}
    for f in S.FOLDS:
        series = [S.load_daily(ROOT, f, a, key=key) for a in arms]
        common = sorted(set.intersection(*[set(d) for _, d in series]))
        cols = []
        for v, d in series:
            ix = {x: i for i, x in enumerate(d)}
            cols.append(v[[ix[c] for c in common]])
        out[f] = np.column_stack(cols)
    return out


def stationary_idx(n, block, B, rng):
    restart = rng.random((B, n)) < 1. / block
    restart[:, 0] = True
    fresh = rng.integers(n, size=(B, n))
    t = np.arange(n)[None]
    start = np.maximum.accumulate(np.where(restart, t, 0), 1)
    return (np.take_along_axis(fresh, start, 1) + t - start) % n


def boot_pooled(J, B=2000, block=10, seed=0):
    """[B, A] bootstrap pooled means (mean over folds of fold bootstrap means), same indices across arms."""
    rng = np.random.default_rng(seed)
    acc = 0
    for f, M in J.items():
        idx = stationary_idx(len(M), block, B, rng)
        acc = acc + M[idx].mean(1)
    return acc / len(J)


def nw_alpha(y, x, lags=5):
    X = np.column_stack([np.ones(len(x)), x])
    b = np.linalg.lstsq(X, y, rcond=None)[0]
    e = y - X @ b
    n = len(y)
    Su = (X * e[:, None])
    Sg = Su.T @ Su
    for L in range(1, lags + 1):
        G = Su[L:].T @ Su[:-L]
        Sg += (1 - L / (lags + 1)) * (G + G.T)
    XtXi = np.linalg.inv(X.T @ X)
    V = XtXi @ Sg @ XtXi
    return b[0], b[0] / np.sqrt(V[0, 0]), b[1]


def main():
    assert len(POOL) == 17
    L = ['# A3 — Selection bias, portfolio diagnostics and data checks', '',
         'Exploratory audit, zero refits. Pool = the 17 h = 5 Ridge/LightGBM arms of FB Tasks 4–6 (the predeclared '
         'selection pool; MLP excluded by the plan). Daily factor-neutral RankIC, seed 7. Generated by '
         '`scripts/fbaudit_selection.py`.', '']
    J = joint(POOL)
    fm = np.array([J[f].mean(0) for f in S.FOLDS])     # [5, A]
    pooled = fm.mean(0)
    w = POOL.index(WINNER)
    # (a) LOFO
    L += ['## (a) Leave-one-fold-out selection', '',
          '| Held-out fold | Selected on other 4 | Its in-sample mean (4 folds) | Its held-out value | Pool median held-out |',
          '|---|---|---|---|---|']
    held = []
    for k, f in enumerate(S.FOLDS):
        ins = np.delete(fm, k, 0).mean(0)
        j = int(np.argmax(ins))
        held.append(fm[k, j])
        L.append(f'| {f} | {POOL[j]} | {ins[j]:+.4f} | {fm[k, j]:+.4f} | {np.median(fm[k]):+.4f} |')
    L += ['', f'Mean held-out value of the LOFO-selected arm: **{np.mean(held):+.4f}** vs the full-sample winner\'s '
          f'in-sample pooled {pooled[w]:+.4f}.', '']
    # (b) stability
    bp = boot_pooled(J)
    freq = np.bincount(bp.argmax(1), minlength=len(POOL)) / len(bp)
    L += ['## (b) Winner stability (joint stationary bootstrap, block 10, B 2000)', '', '| Arm | Pooled | P(argmax) |', '|---|---|---|']
    for j in np.argsort(-pooled)[:8]:
        L.append(f'| {POOL[j]} | {pooled[j]:+.4f} | {freq[j]:.2f} |')
    # (c) RC / SPA
    L += ['', '## (c) Data-snooping tests over the 17-arm pool', '',
          'White Reality Check (RC): statistic max_k pooled_k, null distribution max_k (boot_k − pooled_k). '
          'Hansen SPA (consistent, studentised): t_k = pooled_k/se_k, null recentred at pooled_k·1{t_k ≤ −√(2 ln ln n)}.', '',
          '| Benchmark | Best arm | Best pooled | RC p | SPA p |', '|---|---|---|---|---|']
    rev = joint(['block:reversal16'])
    for bench, Jb in (('zero', None), ('block:reversal16', rev)):
        Jd = J if Jb is None else {f: J[f] - Jb[f] for f in S.FOLDS}
        m = np.mean([Jd[f].mean(0) for f in S.FOLDS], 0)
        b = boot_pooled(Jd, seed=1)
        se = b.std(0, ddof=1)
        rc = float(np.mean((b - m).max(1) >= m.max()))
        n = sum(len(Jd[f]) for f in S.FOLDS)
        tk = m / se
        mu_c = np.where(tk <= -np.sqrt(2 * np.log(np.log(n))), m, 0.)
        spa_stat = max(tk.max(), 0)
        spa = float(np.mean(((b - m + mu_c) / se).max(1).clip(min=0) >= spa_stat))
        L.append(f'| {bench} | {POOL[int(m.argmax())]} | {m.max():+.4f} | {rc:.3f} | {spa:.3f} |')
    # (d) CSCV PBO
    cat = np.vstack([J[f] for f in S.FOLDS])
    blocks = np.array_split(np.arange(len(cat)), 10)
    lam, oos_rank = [], []
    for ins in itertools.combinations(range(10), 5):
        ii = np.concatenate([blocks[i] for i in ins])
        oo = np.concatenate([blocks[i] for i in range(10) if i not in ins])
        j = int(np.argmax(cat[ii].mean(0)))
        r = (cat[oo].mean(0) < cat[oo].mean(0)[j]).sum() + 1      # 1 = worst
        om = r / (len(POOL) + 1)
        lam.append(np.log(om / (1 - om))); oos_rank.append(r)
    pbo = float(np.mean(np.array(lam) <= 0))
    L += ['', '## (d) Probability of backtest overfitting (CSCV, 10 chronological blocks, 252 splits)', '',
          f'PBO = **{pbo:.2f}**; median out-of-sample rank of the in-sample best = {np.median(oos_rank):.0f} of 17 '
          '(17 = best).', '']
    # (e) shrinkage
    se = (bp - bp.mean(1, keepdims=True)).std(0, ddof=1)   # noise of each arm's deviation from the pool mean
    mu = pooled.mean()
    tau2 = max(0., pooled.var(ddof=1) - np.mean(se ** 2))
    shr = mu + tau2 / (tau2 + se ** 2) * (pooled - mu)
    L += ['## (e) Empirical-Bayes shrinkage of the 17 pooled means', '',
          f'Grand mean {mu:+.4f}; between-arm variance beyond noise τ² = {tau2:.2e} (SD {np.sqrt(tau2):.4f}); mean SE of each arm deviation from the pool mean '
          f'{se.mean():.4f}. Winner {WINNER}: raw {pooled[w]:+.4f} → shrunk **{shr[w]:+.4f}**. (Noise = bootstrap SD of each arm minus the pool mean, which accounts for shared dates; '
          'treat as indicative.)', '']
    # (f) sign
    k5 = int((fm > 0).all(0).sum())
    L += ['## (f) Fold-sign consistency', '',
          f'Arms in the pool with 5/5 positive fold means: {k5} of 17 ({", ".join(POOL[j] for j in np.flatnonzero((fm > 0).all(0)))}). '
          'For one predeclared contrast, P(5/5 same sign | null, independent symmetric folds) = 1/16 two-sided; '
          'a one-sided sign test on 5/5 gives p = 1/32 = 0.031. Folds share a model-building pipeline and adjacent '
          'training windows, so they are not fully independent.', '']
    # portfolios
    L += ['## Portfolio diagnostics (frozen seed-7 predictions; FB simulator, read-only import)', '',
          'Gross = cost 0. Break-even cost = mean gross daily return / mean daily turnover (one unit of turnover = '
          'trading 100% of NAV once). Pure-alpha book = Σ book weights × 1-day factor-neutral return (beta × market '
          'removed, sector-demeaned): what the book earns from stock selection alone. Style exposures = mean daily '
          'book-weighted z-score.', '',
          '| Arm | Rule | Gross Sharpe | Net Sharpe | Gross ann. | Cost drag ann. | Turnover/day | Break-even cost (bp) | Beta | Pure-alpha ann. | Pure-alpha Sharpe | Exp. beta-z | Exp. dvol-z | Exp. ret60-z | Exp. vol60-z |',
          '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    acc = {}
    for f in S.FOLDS:
        fb = load_fb(f, 5)
        ev = fb.evaluate
        expo = D.exposures(fb, ev, 'full')[..., -4:]
        r1 = np.zeros((len(ev), fb.price.shape[0])); ok1 = np.zeros_like(r1, bool)
        for d, t in enumerate(ev):
            if t + 1 < fb.price.shape[1]:
                g = fb.observed[:, t] & fb.observed[:, t + 1] & fb.eligible[:, t]
                r1[d] = np.where(g, fb.price[:, t + 1] / np.maximum(fb.price[:, t], 1e-12) - 1, 0); ok1[d] = g
        n1 = np.where(ok1, _neutralise(r1, ok1, fb.beta[:, ev].T.astype(np.float64), fb.sectors), 0.)
        mkt = np.array([r1[d][ok1[d]].mean() if ok1[d].any() else 0. for d in range(len(ev))])
        for a in PORT_ARMS:
            pred = S.load_pred(ROOT, f, a)['prediction'].astype(np.float64)
            for rule in ('A_top10', 'B_sector_ls', 'D_beta_ls'):
                W = weights_rule(pred, fb, ev, rule)
                g = simulate(W, fb, ev, cost=0.)
                n = simulate(W, fb, ev, cost=.001)
                k = len(n['net'])
                book = np.array([W[max(0, d - 4):d + 1].sum(0) / 5 for d in range(k)])
                turn = (g['net'] - n['net']) / .001
                c = acc.setdefault((a, rule), {k_: [] for k_ in ('gross', 'net', 'turn', 'alpha', 'mkt', 'expo')})
                c['gross'].append(g['net']); c['net'].append(n['net']); c['turn'].append(turn)
                c['alpha'].append((book * n1[:k]).sum(1)); c['mkt'].append(mkt[:k])
                c['expo'].append(np.einsum('dn,dnk->dk', book, expo[:k]))
        print('portfolio fold', f, flush=True)
    sh = lambda x: x.mean() / max(x.std(ddof=1), 1e-12) * np.sqrt(252)
    alpha_rows = []
    for (a, rule), c in acc.items():
        g, n, t, al, mk = (np.concatenate(c[k]) for k in ('gross', 'net', 'turn', 'alpha', 'mkt'))
        ex = np.vstack(c['expo']).mean(0)
        beta = np.cov(n, mk)[0, 1] / mk.var(ddof=1)
        L.append(f'| {a} | {rule} | {sh(g):+.2f} | {sh(n):+.2f} | {g.mean() * 252:+.3f} | {(g - n).mean() * 252:.3f} | '
                 f'{t.mean():.3f} | {g.mean() / max(t.mean(), 1e-12) * 1e4:+.1f} | {beta:+.2f} | {al.mean() * 252:+.3f} | '
                 f'{sh(al):+.2f} | ' + ' | '.join(f'{x:+.2f}' for x in ex) + ' |')
        if rule == 'A_top10':
            alpha_rows.append((a, *nw_alpha(n, mk)))
    L += ['', '### Long-only rule A: net returns regressed on the equal-weight market (Newey–West, 5 lags)', '',
          '| Arm | Alpha ann. | t(alpha) | Beta |', '|---|---|---|---|']
    for a, al, t, b in alpha_rows:
        L.append(f'| {a} | {al * 252:+.3f} | {t:+.2f} | {b:.2f} |')
    # data checks
    o = np.load(OHLCV); z = np.load(PANEL)
    ident = z['identity_ok'].astype(bool)
    dates = z['dates'].astype('datetime64[D]')
    dev = dates < np.datetime64('2024-01-01')
    ohl = o['ohlcv'][ident][:, dev]
    obs = z['mask'][ident][:, dev].astype(bool)
    tick = z['tickers'][ident]
    zv = (ohl[..., 4] == 0) & obs
    cl = ohl[..., 3]
    same = np.zeros_like(zv); same[:, 1:] = np.isclose(cl[:, 1:], cl[:, :-1])
    years = dates[dev].astype('datetime64[Y]').astype(int) + 1970
    L += ['', '## Data checks', '', f'Zero-volume observed cells (pre-2024): {int(zv.sum())}; of these, close unchanged from the '
          f'previous day: {int((zv & same).sum())} ({(zv & same).sum() / max(zv.sum(), 1):.0%}).', '',
          '| Year | Zero-volume cells |', '|---|---|']
    for y in np.unique(years):
        L.append(f'| {y} | {int(zv[:, years == y].sum())} |')
    top = np.argsort(-zv.sum(1))[:10]
    L += ['', 'Top stocks by zero-volume cells: ' + ', '.join(f'{tick[i]} ({int(zv[i].sum())})' for i in top), '']
    zd = zv.sum(0)
    sys.path.insert(0, 'src')
    from hypershift.screening.data import load_panel
    pan = load_panel(PANEL, 2023, train_stride=1)
    el = pan.eligible[:, :zv.shape[1]]
    L += [f'Zero-volume cells that are FB-eligible: {int((zv & el).sum())}; of which in 2019–2023: '
          f'{int((zv & el)[:, years >= 2019].sum())}. Per stock (eligible, 2019–2023): ' +
          ', '.join(f'{tick[i]} {int((zv & el)[i, years >= 2019].sum())}' for i in top[:3]) +
          '. First non-zero-volume date for those stocks: ' +
          ', '.join(f'{tick[i]} {dates[dev][np.argmax(obs[i] & ~zv[i])]}' for i in top[:3]) + '.', '']
    L += [f'Dates with ≥ 100 zero-volume stocks: {int((zd >= 100).sum())} (' +
          ', '.join(str(d) for d in dates[dev][zd >= 100][:10]) + ').']
    (OUT / 'A3_SELECTION_PORTFOLIO.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
