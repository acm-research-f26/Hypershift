"""WP-A extension (ledgered): reuse the strongest existing saved candidate, the style-only LightGBM book (A13,
net Sharpe +1.11 at 5 bp, 2019-2023, post hoc), in the WP-A engine with borrow costs and FF attribution.
Question: is its performance explained by standard factor exposures?

  python scripts/strategy_style_book.py   -> docs/strategy_20261022/STYLE_BOOK.md
Exploratory: 2019-2023 inspected; survivor universe; predictions from results/FBAUDIT_20261022/matched (seed 7).
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
from hypershift.strategy import study as ST, engine as EN, factors as FA  # noqa: E402

MAT = Path('results/FBAUDIT_20261022/matched')
FB = Path('results/FEATBENCH_SP500_20261022')
OUT = Path('docs/strategy_20261022/STYLE_BOOK.md')
CELLS = ('style_residual', 'style_neutral', 'full_residual')


def main():
    d = ST.load_data()
    ff = FA.load_ff('data/factors')
    idx = {str(x): i for i, x in enumerate(d.dates.astype(str))}
    L = ['# Existing candidate re-tested: style-only LightGBM book (2019–2023, exploratory)', '',
         '**Inputs.** Saved predictions from the matched 2×2 (A11, seed 7; features = beta, log dollar volume [corrected], '
         '60-day return, 60-day volatility, sector). The signal on date t is used for a trade at the open of t+1. '
         'Rebalance every 5 trading days.', '',
         '**Books:**',
         '- **LS:** sector-neutral top/bottom 10%, 30% hold band, beta-hedged, borrow 50 bp/yr.',
         '- **LO:** top 20%, 40% band, against an equal-weight benchmark on the same days.', '',
         'Costs 10 bp per unit traded. Generated by `scripts/strategy_style_book.py`.', '',
         '| Cell / book | Net ann. | Net Sharpe or active IR [95% CI] | Traded/yr | FF alpha ann. (t) | Mkt-RF | SMB | HML | RMW | CMA | MOM | STREV | R² |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for cell in CELLS:
        sc = {}
        for f in (2019, 2020, 2021, 2022, 2023):
            p = np.load(MAT / str(f) / f'{cell}_s7.npz')
            for k, (day, row) in enumerate(zip(p['dates'], p['pred'])):
                if k % 5 == 0 and str(day) in idx and idx[str(day)] + 1 < len(d.dates):
                    sc[idx[str(day)] + 1] = row.astype(np.float64)
        end = int(np.searchsorted(d.dates, np.datetime64('2023-12-31'), side='right') - 1)
        ls = EN.run(sc, d, mode='LS', top=.1, band=.3, execution='open', cost_bp=10, borrow_bp=50, end=end)
        lo = EN.run(sc, d, mode='LO', top=.2, band=.4, execution='open', cost_bp=10, borrow_bp=0, end=end)
        bench = EN.benchmark_ew(sc, d, execution='open', cost_bp=10, end=end)
        yrs = len(ls['net']) / 252
        for name, series, tr in ((f'{cell} LS', ls['net'], ls['traded'].sum() / yrs),
                                 (f'{cell} LO active', lo['net'] - bench['net'], lo['traded'].sum() / yrs)):
            s = ST.ir_stats(series)
            a = FA.attribute(series, ls['dates'], ff)
            b = a['betas']
            L.append(f"| {name} | {s['ann_mean']:+.3f} | {s['ir']:+.2f} [{s['ci'][0]:+.2f}, {s['ci'][1]:+.2f}] | {tr:.2f} | "
                     f"{a['alpha_ann']:+.3f} ({a['t']:+.2f}) | " + ' | '.join(f'{b[k]:+.2f}' for k in FA.FACTORS) + f" | {a['r2']:.2f} |")
        print(cell, flush=True)
    L += ['', '**Reading rule** (stated before the numbers): if the FF alpha t-statistic is below 2 and R² is high, the book is '
          'a factor-exposure portfolio. It then supplies no incremental value over buying those factors cheaply. Stop it as '
          'a product candidate; at most, list it as a factor tilt.']
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
