"""FB audit Task 1: independent recompute, per-contrast power, block-length sensitivity, non-superiority, seeds.

  python scripts/fbaudit_stats.py   -> docs/audit_20261022/A1_RECOMPUTE_POWER.md
Daily series are recomputed from saved predictions.npz with fresh Spearman code (not featbench's evaluator).
"""
import csv
import sys
from pathlib import Path

import numpy as np
from scipy.stats import norm, t as tdist

sys.path.insert(0, 'src')
from hypershift.fbaudit import stats as S  # noqa: E402

ROOT = Path('results/FEATBENCH_SP500_20261022')
OUT = Path('docs/audit_20261022')
DELTA = 0.010
_cache = {}


def daily(arm, fold, seed=7):
    k = (arm, fold, seed)
    if k not in _cache:
        z = S.load_pred(ROOT, fold, arm, seed)
        _cache[k] = (S.spearman_daily(z['prediction'], z['neutral'], z['mask']), z['dates'].astype(str),
                     z['mask'].sum(1))
    return _cache[k]


def paired(a, b=None, sa=7, sb=7):
    out = {}
    for f in S.FOLDS:
        va, da, _ = daily(a, f, sa)
        if b is None:
            out[f] = va
            continue
        vb, db, _ = daily(b, f, sb)
        ib = {d: i for i, d in enumerate(db)}
        out[f] = np.array([va[i] - vb[ib[d]] for i, d in enumerate(da) if d in ib])
    return out


def f4(x):
    return f'{x:+.4f}'


def ci(r, k='ci95'):
    return f'[{r[k][0]:+.4f}, {r[k][1]:+.4f}]'


FB_PAIRS = [('lgbm:rich', 'ridge:rich'), ('ridge:rich', 'block:reversal16'), ('lgbm:rich', 'block:reversal16'),
            ('lgbm:rich', 'lgbm:price'), ('mlp:rich', 'ridge:rich'), ('ridge:lags', 'block:reversal16'),
            ('ridge:rich:sector', 'ridge:rich'), ('ridge:rich:residual', 'ridge:rich'),
            ('lgbm:rich:sector', 'lgbm:rich'), ('lgbm:rich:residual', 'lgbm:rich')] + \
           [(f'{m}:rich:raw:5:{r}', f'{m}:rich') for m in ('ridge', 'lgbm')
            for r in ('raw', 'cs_rank', 'sector_z', 'volscaled_z')]
POWER = [('lgbm:rich:residual', 'lgbm:rich'), ('lgbm:rich:residual', 'block:reversal16'), ('lgbm:rich:residual', None),
         ('ridge:rich:sector', 'ridge:rich'), ('lgbm:rich', 'ridge:rich'), ('lgbm:rich', 'lgbm:price'),
         ('ridge:rich', 'block:reversal16'), ('block:reversal16', None), ('block:l1', None)]
METHODS = [('stationary', 5), ('stationary', 10), ('stationary', 20), ('stationary', 40), ('mbb', 10),
           ('nw', 5), ('nw', 10), ('nw', 20)]


def name(a, b):
    return f'{a} − {b}' if b else f'{a} (vs 0)'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    fb = {r['contrast']: r for r in csv.DictReader(open('docs/featbench_20261022/fb_PAIRED.csv', encoding='utf-8'))}
    L = ['# A1 — Independent recompute, power and block-length sensitivity', '',
         'Exploratory audit. Daily factor-neutral RankIC series recomputed from the saved `predictions.npz` with fresh '
         'Spearman code (`fbaudit.stats.spearman_daily`), not the featbench evaluator. Pooled = mean of 5 fold means '
         '(2019–2023), seed 7 unless stated. Generated by `scripts/fbaudit_stats.py`.', '']
    # (a) recompute
    L += ['## (a) Recompute of the 18 FB family contrasts', '',
          '| Contrast | FB pooled | Audit pooled | abs diff | FB 95% CI | Audit 95% CI (stationary, block 10) |',
          '|---|---|---|---|---|---|']
    maxdiff = 0
    for a, b in FB_PAIRS:
        r = S.pooled(paired(a, b), 'stationary', 10)
        k = f'{a} − {b}'
        fp = float(fb[k]['pooled'])
        maxdiff = max(maxdiff, abs(fp - r['pooled']))
        L.append(f"| {k} | {f4(fp)} | {f4(r['pooled'])} | {abs(fp - r['pooled']):.1e} | "
                 f"[{float(fb[k]['ci_lo']):+.4f}, {float(fb[k]['ci_hi']):+.4f}] | {ci(r)} |")
    arms = sorted({x for p in FB_PAIRS for x in p})
    saved_vs_mine = max(np.abs(S.load_daily(ROOT, f, a)[0] - daily(a, f)[0]).max() for a in arms for f in S.FOLDS)
    L += ['', f'Max abs(FB pooled − audit pooled) = {maxdiff:.2e}; max abs(saved daily − recomputed daily) over '
          f'{len(arms)} arms × 5 folds = {saved_vs_mine:.2e}. CIs differ only by bootstrap random draws.', '']
    # (b) power
    L += ['## (b) Per-contrast uncertainty and power', '',
          'SE of the pooled mean under different dependence models (sb = stationary bootstrap with mean block k; MBB = '
          'circular moving block; NW = Newey–West with k lags, folds combined). MDE = 2.8 × SE (80% power, two-sided '
          'α .05). Fold-t MDE uses only the 5 fold means (t, 4 df). Non-overlap spread = max − min of the pooled mean '
          'over the 5 every-5th-day subsamples. Days for an MDE use the per-day long-run variance from the block-10 '
          'stationary bootstrap.', '',
          '| Contrast | Pooled | Daily SD | SE sb5 | SE sb10 | SE sb20 | SE sb40 | SE MBB10 | SE NW5 | SE NW10 | SE NW20 '
          '| MDE (sb10) | Fold-t MDE | Non-overlap spread | Days for 0.02 | Days for 0.01 |',
          '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    pw = {}
    for a, b in POWER:
        ser = paired(a, b)
        res = [S.pooled(ser, m, block=k, B=3000) for m, k in METHODS]
        r10 = res[1]
        fm = np.array(list(r10['per_fold'].values()))
        tm = (tdist.ppf(.975, 4) + tdist.ppf(.8, 4)) * fm.std(ddof=1) / np.sqrt(5)
        lrv = float(np.mean([S.pooled({0: s}, 'stationary', 10, 3000)['se'] ** 2 * len(s) for s in ser.values()]))
        sub = [np.mean([S.nonoverlap(s, 5)[o] for s in ser.values()]) for o in range(5)]
        sd = np.mean([s.std(ddof=1) for s in ser.values()])
        pw[name(a, b)] = dict(lrv=lrv, se=r10['se'], pooled=r10['pooled'])
        L.append(f"| {name(a, b)} | {f4(r10['pooled'])} | {sd:.4f} | " + ' | '.join(f"{r['se']:.4f}" for r in res) +
                 f" | {2.8 * r10['se']:.4f} | {tm:.4f} | {max(sub) - min(sub):.4f} | {lrv * (2.8 / .02) ** 2:.0f} | "
                 f"{lrv * (2.8 / .01) ** 2:.0f} |")
    L += ['', '### Power of a single-series prospective test (two-sided α .05, block-10 long-run variance)', '',
          '| Contrast | LRV per day | SE at 250 d | P(detect) θ=0.003 | θ=0.006 | θ=0.010 | θ=0.020 | Days for 80% at θ=0.006 |',
          '|---|---|---|---|---|---|---|---|']
    for k in ('lgbm:rich:residual − block:reversal16', 'lgbm:rich:residual − lgbm:rich', 'lgbm:rich:residual (vs 0)'):
        lrv = pw[k]['lrv']
        se = np.sqrt(lrv / 250)
        P = lambda th: norm.cdf(th / se - 1.96) + norm.cdf(-th / se - 1.96)
        L.append(f"| {k} | {lrv:.4f} | {se:.4f} | {P(.003):.2f} | {P(.006):.2f} | {P(.010):.2f} | {P(.020):.2f} | "
                 f"{lrv * (2.8 / .006) ** 2:.0f} |")
    # (c) sampling floor
    L += ['', '## (c) Daily RankIC variability vs the pure sampling floor', '',
          'If the true daily IC were constant, a cross-sectional Spearman over n stocks would have SD ≈ 1/√(n−1). Excess '
          'SD is day-to-day variation of the true cross-sectional IC (factor/regime variation), which more stocks '
          'cannot remove.', '',
          '| Arm | Mean n | Floor 1/√(n−1) | Observed daily SD (neutral) | Share of variance above floor |', '|---|---|---|---|---|']
    for a in ('block:reversal16', 'block:l1', 'ridge:rich', 'lgbm:rich', 'lgbm:rich:residual'):
        sds, ns = [], []
        for f in S.FOLDS:
            v, _, n = daily(a, f)
            sds.append(v.std(ddof=1)); ns.append(n.mean())
        fl = 1 / np.sqrt(np.mean(ns) - 1)
        sd = np.mean(sds)
        L.append(f'| {a} | {np.mean(ns):.0f} | {fl:.4f} | {sd:.4f} | {1 - fl ** 2 / sd ** 2:.0%} |')
    # (d) non-superiority / TOST
    L += ['', f'## (d) Non-superiority and equivalence (δ = {DELTA}, predeclared T1)', '',
          '"Rules out gain ≥ δ" = upper 90% bound < δ. "Rules out loss ≥ δ" = lower 90% bound > −δ. "Equivalent" = '
          'both.', '',
          '| Contrast | Pooled | 90% CI | Rules out gain ≥ δ | Rules out loss ≥ δ | Equivalent within ±δ |',
          '|---|---|---|---|---|---|']
    for a, b in FB_PAIRS:
        r = S.pooled(paired(a, b), 'stationary', 10)
        lo, hi = r['ci90']
        L.append(f"| {a} − {b} | {f4(r['pooled'])} | {ci(r, 'ci90')} | {'yes' if hi < DELTA else 'no'} | "
                 f"{'yes' if lo > -DELTA else 'no'} | {'yes' if lo > -DELTA and hi < DELTA else 'no'} |")
    # (e) seeds
    pv = [S.pooled(paired('lgbm:rich', None, s), 'stationary', 10, 2000)['pooled'] for s in (7, 19, 42)]
    se_date = S.pooled(paired('lgbm:rich'), 'stationary', 10)['se']
    cor = np.mean([np.corrcoef(daily('lgbm:rich', f, 7)[0], daily('lgbm:rich', f, s)[0])[0, 1]
                   for f in S.FOLDS for s in (19, 42)])
    L += ['', '## (e) Seed vs date uncertainty (lgbm:rich, seeds 7/19/42)', '', '| Quantity | Value |', '|---|---|',
          f'| pooled by seed | {", ".join(f4(x) for x in pv)} |',
          f'| between-seed SD of pooled | {np.std(pv, ddof=1):.4f} |',
          f'| date SE of pooled (sb10) | {se_date:.4f} |',
          f'| mean daily corr, seed 7 vs 19/42 | {cor:.3f} |']
    (OUT / 'A1_RECOMPUTE_POWER.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
