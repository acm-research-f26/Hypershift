"""Three focused checks of the reusable PIT infrastructure (sector timing, opening-price accounting, delistings and
identity) on the completed style-book test. Does not rescore the style book.

  python scripts/pit_infra_checks.py   -> docs/strategy_lazyprices_20261023/INFRA_CHECKS.md
"""
import os
import sys
from datetime import date
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
from hypershift.data import pit_sp500 as PS  # noqa: E402
from hypershift.strategy import pit as SP, pit_engine as PE  # noqa: E402

OUT = Path('docs/strategy_lazyprices_20261023/INFRA_CHECKS.md')
SCORES = Path('results/STRATEGY_PIT_20261023/scores_P.npz')


def merger_types(symbols):
    """{symbol: set of Alpaca merger record types} for acquiree symbols, 2016-2023 (Alpaca corporate actions)."""
    from alpaca.data.historical.corporate_actions import CorporateActionsClient
    from alpaca.data.requests import CorporateActionsRequest
    from alpaca.data.enums import CorporateActionsType as C
    c = CorporateActionsClient(os.environ['APCA_API_KEY_ID'], os.environ['APCA_API_SECRET_KEY'])
    out = {}
    for j in range(0, len(symbols), 50):
        r = c.get_corporate_actions(CorporateActionsRequest(
            symbols=symbols[j:j + 50], types=[C.CASH_MERGER, C.STOCK_MERGER, C.STOCK_AND_CASH_MERGER, C.WORTHLESS_REMOVAL],
            start=date(2016, 1, 1), end=date(2024, 6, 30))).dict()
        for kind, recs in r.items():
            for x in recs:
                s = x.get('acquiree_symbol') or x.get('symbol')
                if s:
                    out.setdefault(s, set()).add(kind)
    return out


def main():
    z = np.load(SP.NPZ)
    d, fb = SP.load()
    labels = list(z['labels'])
    dates = d.dates
    N, T = d.observed.shape
    observed = d.observed
    obs_r = observed.copy()
    obs_r[:, 0] = False
    obs_r[:, 1:] &= observed[:, :-1]
    L = ['# Infrastructure checks on the PIT panel (2026-10-23)', '',
         'Generated by `scripts/pit_infra_checks.py`. These checks verify the reusable data and engine for the next '
         'strategy; they do not rescore or rehabilitate the stopped style book.', '']

    # ---- A. sector timing
    k126 = np.full(N, -1)
    for i in range(N):
        idx = np.flatnonzero(obs_r[i])
        if len(idx) >= 126:
            k126[i] = idx[125]
    early = d.eligible & (np.arange(T)[None] < k126[:, None])
    sc = np.load(SCORES)
    days = sc['days']
    sig = days - 1
    held = PE.run_pit({int(k): s for k, s in zip(days, sc['s'])}, d, mode='LS', top=.1, band=.3, cost_bp=0, borrow_bp=50,
                      trace=True)
    w0 = held['w_start']
    t_run = np.searchsorted(dates, held['dates'])
    pos_early = int(sum(((w0[k] != 0) & early[:, t_run[k] - 1]).sum() for k in range(len(t_run))))
    sig_early = int(early[:, sig].sum())
    train_early = int((early & (dates[None] < np.datetime64('2018-01-01'))).sum())
    ent_early_eval = sorted({labels[i] for i, t in zip(*np.nonzero(early)) if dates[t] >= np.datetime64('2018-01-01')})
    ref = z['gics_ref']
    r_all = np.zeros((N, T))
    with np.errstate(divide='ignore', invalid='ignore'):
        r_all[:, 1:] = np.where(obs_r[:, 1:], d.close[:, 1:] / d.close[:, :-1] - 1, 0)
    s63 = PS.sector_proxy(r_all, obs_r, ref, window=63)
    s126 = z['sectors']
    m = ref >= 0
    L += ['## A. Sector assignment timing', '',
          '**Implementation.** `pit_sp500.sector_proxy` assigns each entity the GICS sector whose leave-one-out '
          'survivor basket correlates most with the entity\'s first 126 *observed* daily returns (from 2016-01-04 or '
          'listing). Eligibility starts after 64 consecutive observed sessions. So between eligibility and the 126th '
          'return, the sector used at a signal close depends on up to 62 later returns: **look-ahead**.', '',
          '| Exposure | Count |', '|---|---|',
          f'| Eligible member-days before the 126th return (all) | {int(early.sum())} |',
          f'| ... of which before 2018 (training rows only) | {train_early} |',
          f'| Weekly signal cross-sections in 2018–2023: stock-signals affected | {sig_early} |',
          f'| Arm P positions held on affected days (stock-days with nonzero weight) | {pos_early} |',
          f'| Entities affected inside 2018–2023 | {len(ent_early_eval)}: ' + ', '.join(ent_early_eval[:20]) + ' |', '',
          f'**Size of the effect.** A causal variant using only the first 63 returns (all before the first possible '
          f'eligible day) changes the sector of {int((s63 != s126).sum())} of {N} entities; agreement with current '
          f'GICS on survivors is {np.mean(s63[m] == ref[m]):.3f} (63 returns) vs {np.mean(s126[m] == ref[m]):.3f} (126). ',
          '**Current-GICS dependence.** The reference baskets are built from *survivors* (2026 constituents) labelled '
          'with *current* GICS. Basket returns are contemporaneous (no timing leak), but the labels are a 2026 '
          'classification and only survivors define the baskets: a historical-classification limitation, not an '
          'information-timing leak.', '',
          '**Disposition.** The look-ahead touches a small set of signals (above) and the stopped style book\'s decision '
          '(net Sharpe +0.11, with a GICS-sector sensitivity of −0.17) cannot plausibly move to the 0.60 continuation '
          'threshold through it; no rerun. **Pipeline fix:** the panel now also stores `sectors_causal` (63-return '
          'rule). The next strategy uses **Fama–French 12 industries from EDGAR SIC codes** instead, which removes both '
          'the return-based proxy and the current-GICS dependence (SIC is the registrant\'s latest code: still not a '
          'dated history).', '']

    # ---- B. opening-price accounting
    r_chk, kind = PS.clean_returns(z['raw_close'], z['raw_open'], z['all_close'], observed)
    for lab, day in (('UA', '2016-04-08'),):
        i, t = labels.index(lab), int(np.searchsorted(dates, np.datetime64(day)))
        r_chk[i, t], kind[i, t] = 0., 'neutralised'
    c2, o2 = PS.price_index(z['raw_close'], z['raw_open'], r_chk, kind, observed)
    ok = observed
    dc = np.nanmax(np.abs(c2[ok] / z['close'][ok] - 1))
    do = np.nanmax(np.abs(o2[ok] / z['open'][ok] - 1))
    neut = list(zip(*np.nonzero(z['kind'] == 'neutralised')))
    held_neut = []
    for i, t in neut:
        k = np.searchsorted(t_run, t)
        if k < len(t_run) and t_run[k] == t:
            held_neut.append((labels[i], str(dates[t]), float(w0[k][i])))
    L += ['## B. Opening-price accounting', '',
          '**Construction** (`pit_sp500.price_index`, test `test_price_index_open_uses_no_same_day_close`). The close '
          'index cumulates the cleaned daily returns; the open is `index_t × raw_open_t / raw_close_t`, which equals '
          '`index_(t−1) × adjustment_t × raw_open_t / raw_close_(t−1)`: it uses the previous close, the day\'s raw '
          'open and the ex-date adjustment factor, **never the same day\'s close** (the test changes the day\'s close '
          'and the open is unchanged). On an ex-dividend or split day the overnight return includes the '
          'adjustment, which is the economic return of a holder. On a neutralised day open = close = previous close.', '',
          f'- Rebuilding the stored panel with the tested function: max relative difference close {dc:.1e}, open {do:.1e}.',
          f'- Engine fills: `run_pit` trades at `open_t` after drifting weights with close(t−1)→open(t); P&L from '
          f'open(t)→close(t) accrues to the new weights. Signals use closes up to t−1 only (`test_open_execution_no_lookahead`).',
          f'- Neutralised stock-days: {len(neut)} in total, {sum(bool(z["member"][i, t]) for i, t in neut)} on member days '
          f'(the 12 listed in `PIT_DATA.md`) and {sum(not z["member"][i, t] for i, t in neut)} on non-member days ('
          + ', '.join(f'{labels[i]} {dates[t]}' for i, t in neut if not z["member"][i, t]) + ').',
          f'- Arm P held a nonzero weight on {sum(c != 0 for _, _, c in held_neut)} of them, all hedge-basket sized (max |weight| '
          f'{max([abs(c) for _, _, c in held_neut] + [0]):.4f}): ' +
          (', '.join(f'{a} {b} ({c:+.4f})' for a, b, c in held_neut if c != 0) or 'none') +
          '. No long or short leg position sat on a neutralised day, so the zeroed returns cannot distort the result.', '']

    # ---- C. delistings and identity
    last = z['last']
    fail = z['failure']
    member = z['member']
    dl = held['delisted_weight']
    events = []
    for k in np.flatnonzero(dl > 0):
        t = t_run[k]
        gone = [i for i in range(N) if last[i] == t - 1 and w0[k][i] != 0]
        for i in gone:
            events.append((labels[i], str(dates[t - 1]), float(w0[k][i]), bool(member[i, t - 1]), bool(fail[i])))
    syms = sorted({s for e in events for s in e[0].split('|')})
    try:
        mt = merger_types(syms)
    except Exception as e:  # network / credentials
        mt = {}
        print('corporate actions unavailable:', e)
    fl = []
    for i in np.flatnonzero(fail):
        mm = np.flatnonzero(member[i])
        fl.append((labels[i], str(dates[mm[-1]]) if len(mm) else '-', str(dates[last[i]]), bool(member[i, last[i]])))
    L += ['## C. Delistings and identity', '',
          f'**Failure flags vs terminal sensitivities.** `failure` is set for {int(fail.sum())} entities (last close below half '
          'the close 60 sessions earlier, regardless of membership). The −100%/−30% sensitivities applied the terminal return '
          'to all of them, but a terminal return only acts on a position still held at the last bar:', '',
          '| Entity | Last member day | Last bar | Member at last bar |', '|---|---|---|---|'] +          [f'| {a} | {b} | {c} | {d_} |' for a, b, c, d_ in fl] +          ['', 'Entities that left the index years before their last bar were exited at the next rebalance after removal, '
          'so only the entities that were members at their last bar can carry a terminal loss. This reconciles "4 '
          'flagged" with "2 member failures".', '',
          f'**Delisting liquidations in arm P (2018–2023):** {len(events)} positions, total |weight| '
          f'{sum(abs(e[2]) for e in events):.3f}.', '',
          '| Entity | Last bar | Weight at last bar | Member at last bar | Failure | Alpaca record |', '|---|---|---|---|---|---|']
    for a, b, c, mm, f in events:
        rec = ', '.join(sorted(set().union(*[mt.get(s, set()) for s in a.split('|')]))) or 'none found'
        L.append(f'| {a} | {b} | {c:+.4f} | {mm} | {f} | {rec} |')
    gaps = member & ~observed
    runs = []
    for i in np.flatnonzero(gaps.any(1)):
        g = np.r_[0, gaps[i].astype(int), 0]
        st, en = np.flatnonzero(np.diff(g) == 1), np.flatnonzero(np.diff(g) == -1)
        runs += [(labels[i], str(dates[s]), int(e - s)) for s, e in zip(st, en)]
    runs.sort(key=lambda x: -x[2])
    held_gap = int(sum(((w0[k] != 0) & ~observed[:, t_run[k]]).sum() for k in range(len(t_run))))
    L += ['', 'Alpaca merger records were found only from 2020 onward (its corporate-action history appears to start '
          'around then); earlier events are classified from the public record only where it matters below.', '',
          '**Treatment by case:**',
          '- *Cash merger*: the target trades until the deal closes near the deal price, so liquidation at the last '
          'close captures the economic exit (minus any final-day spread).',
          '- *Stock merger*: the last close reflects exchange ratio × acquirer price; liquidation to cash at that close '
          'approximates selling the received shares at the next open (overnight acquirer move ignored).',
          '- *Failure*: last listed close; post-delisting OTC value absent (sensitivity −100% / −30%).',
          '- *Leaving the index while listed*: exited at the next weekly rebalance (`run_pit`), never kept as a stub.',
          f'- *Halts / missing bars while a member*: {int(gaps.sum())} member-days in {len(set(r[0] for r in runs))} '
          f'entities; longest runs: ' + ', '.join(f'{a} from {b} ({c} days)' for a, b, c in runs[:6]) +
          f'. A held name with no bar keeps its weight at zero return until its bars resume or it is liquidated as '
          f'delisted; arm P had {held_gap} held stock-days without a bar.', '',
          '**Ticker identity vs company identity.** An entity is one Alpaca company series (`asof` = last day of each '
          'fja05680 membership interval), merged across intervals whose daily returns are identical; its label lists '
          'the historical tickers (e.g. `GEN|NLOK|SYMC`, `CBS|PARA|VIAC`). A reused ticker (DOW = Dow Chemical until '
          '2017 and Dow Inc from 2019) maps to different entities through different `asof` dates. Alpaca\'s `asof` '
          'history can splice predecessor companies around mergers (pre-membership bars of DOW, DD, ARNC); these bars '
          'only feed features before membership. **Identity break found:** FBHS (Fortune Brands Home & Security) '
          'ends 2022-12-14 although the company continued as FBIN after the MasterBrand spin-off; the `asof` series '
          'did not follow the rename, so the engine treated it as a delisting (arm P weight −0.0001, negligible). The '
          'general check (a liquidated entity whose CIK keeps filing after its last bar) is run in `CIK_MAP.md`. '
          '**For SEC data the identity key is the CIK**, mapped per entity and '
          'verified separately (`docs/strategy_lazyprices_20261023/CIK_MAP.md`).', '',
          '**Remaining limitations.** No post-delisting returns; Alpaca corporate-action records are unreliable for '
          'spin-offs (handled by A1); sector/industry codes are current, not dated; membership is the Wikipedia-derived '
          'fja05680 list; no prices before 2016.']
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
