"""BC review Task 2: does turnover control make the market-neutral book survive costs? (predeclared D4)

  python scripts/bcreview_cost.py   -> docs/audit_20261022/A8_COST.md
Exploratory (2019-2023 inspected). Same book construction for every arm, so economic exposures are matched.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, 'src')
sys.path.insert(0, 'scripts')
from hypershift.featbench.data import load_fb, OHLCV, PANEL  # noqa: E402
from hypershift.fbaudit import stats as S, diag as D, diag2 as D2, book  # noqa: E402
from fbaudit_refit import corrected_fb  # noqa: E402
from fbaudit_selection import stationary_idx  # noqa: E402

COR = Path('results/FBAUDIT_20261022/corrected')
FB_ROOT = Path('results/FEATBENCH_SP500_20261022')
OUT = Path('docs/audit_20261022')
COSTS = (2, 5, 10, 20)
SCHED = ('daily', 'weekly', 'weekly_buffer')
EXEC = ('close1', 'open1')


def sharpe(x):
    return float(x.mean() / max(x.std(ddof=1), 1e-12) * np.sqrt(252))


def main():
    o = np.load(OHLCV); z = np.load(PANEL)
    ohlcv_all = o['ohlcv'][z['identity_ok'].astype(bool)].astype(np.float64)
    acc = {}
    for f in S.FOLDS:
        fb = corrected_fb(load_fb(f, 5), f)
        ev = fb.evaluate
        mask = (fb.y_ok[:, ev] & fb.eligible[:, ev]).T
        full = D.exposures(fb, ev, 'full')
        raw = np.load(COR / str(f) / 'lgbm_rich_raw_es.npz')['pred'].astype(np.float64)
        arms = {'residual LightGBM': np.load(COR / str(f) / 'lgbm_rich_residual_es.npz')['pred'].astype(np.float64),
                'raw LightGBM neutralised': D.neutralise_pred(raw, full, mask),
                'RR': D2.residual_reversal(fb, ev, 21),
                'reversal16': S.load_pred(FB_ROOT, f, 'block:reversal16')['prediction'].astype(np.float64),
                'random': np.random.default_rng(f).normal(size=raw.shape)}
        T = fb.price.shape[1]
        mkt = np.array([np.nanmean(np.where(fb.eligible[:, t] & fb.observed[:, t] & fb.observed[:, t + 1],
                                            fb.price[:, t + 1] / np.maximum(fb.price[:, t], 1e-12) - 1, np.nan))
                        if t + 1 < T else np.nan for t in ev])
        for a, p in arms.items():
            for sc in SCHED:
                for ex in EXEC:
                    out = book.simulate_book(p, fb, ev, sc, ex, ohlcv=ohlcv_all[:, :T])
                    k = len(out['gross'])
                    sty = np.abs(np.einsum('dn,dnk->dk', out['weights'], full[:k, :, -4:])).mean(0)
                    c = acc.setdefault((a, sc, ex), {'g': [], 't': [], 'm': [], 's': []})
                    c['g'].append(out['gross']); c['t'].append(out['traded']); c['m'].append(mkt[:k]); c['s'].append(sty)
        print('fold', f, flush=True)
    L = ['# A8 — Cost-aware market-neutral book (predeclared D4)', '',
         'BC pre-execution review, exploratory (2019–2023 inspected), leak-free predictions.', '',
         '**Book.** Long the top 10% and short the bottom 10% within each sector (0.5 gross per leg), beta-hedged ex '
         'ante with an equal-weight basket of eligible stocks. Weights drift between trades, and hedge trades are costed.', '',
         '**Schedules:**',
         '- `daily`: rebalance every session;',
         '- `weekly`: rebalance every 5 sessions;',
         '- `weekly_buffer`: weekly, entering at the top/bottom 10% of the sector and exiting outside the top/bottom 30%.', '',
         '**Execution.** The signal is computed at close t. `close1` trades at close t+1; `open1` trades at open t+1.', '',
         '**Costs.** c bp per unit of one-way traded notional / NAV. Returns are actual close/open price returns of the '
         'implementable book, not residual labels. Annualised returns are arithmetic.', '',
         'Generated by `scripts/bcreview_cost.py`.', '',
         '| Arm | Schedule | Exec | Gross Sharpe | Net Sharpe 2bp | 5bp [95% CI] | 10bp | 20bp | Gross ann. | Traded/day | Break-even (bp) | Realised beta | Mean abs style exposure (beta, dvol, ret60, vol60) |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    verdict = {}
    for (a, sc, ex), c in acc.items():
        g, t, m = (np.concatenate(c[k]) for k in ('g', 't', 'm'))
        ok = np.isfinite(m)
        net = {cc: g - cc * 1e-4 * t for cc in COSTS}
        idx = stationary_idx(len(g), 10, 2000, np.random.default_rng(0))
        bs = np.array([sharpe(net[5][i]) for i in idx])
        lo, hi = np.quantile(bs, [.025, .975])
        be = g.mean() / max(t.mean(), 1e-12) * 1e4
        beta = np.cov(g[ok], m[ok])[0, 1] / m[ok].var(ddof=1)
        sty = np.mean(c['s'], 0)
        L.append(f'| {a} | {sc} | {ex} | {sharpe(g):+.2f} | {sharpe(net[2]):+.2f} | {sharpe(net[5]):+.2f} [{lo:+.2f}, {hi:+.2f}] | '
                 f'{sharpe(net[10]):+.2f} | {sharpe(net[20]):+.2f} | {g.mean() * 252:+.3f} | {t.mean():.3f} | {be:+.1f} | '
                 f'{beta:+.2f} | ' + ', '.join(f'{x:.2f}' for x in sty) + ' |')
        if sc != 'daily':
            verdict.setdefault(a, {})[(sc, ex)] = sharpe(net[5]) >= .5 and be >= 10
    L += ['', '## D4 verdict ("economically promising" = net Sharpe ≥ 0.5 at 5 bp and break-even ≥ 10 bp, for a weekly schedule under both executions)', '']
    for a, v in verdict.items():
        ok = any(v.get((sc, 'close1')) and v.get((sc, 'open1')) for sc in ('weekly', 'weekly_buffer'))
        L.append(f"- {a}: **{'PROMISING' if ok else 'not promising'}** (" +
                 '; '.join(f'{sc}/{ex}: {"yes" if r else "no"}' for (sc, ex), r in v.items()) + ')')
    (OUT / 'A8_COST.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
